CREATE OR REPLACE FUNCTION public.hu021_cancelar_separacion(
  p_codsep bigint,
  p_motivo text,
  p_observacion_dinero text,
  p_idempotencia uuid
)
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
DECLARE
  v_actor bigint;
  v_rol text;
  v_coduni bigint;
  v_unidad public.unidad%ROWTYPE;
  v_separacion public.separacion%ROWTYPE;
  v_evento public.historialcancelacion%ROWTYPE;
  v_motivo text;
  v_observacion text;
  v_payload jsonb;
  v_estado_unidad text;
  v_resultado jsonb;
BEGIN
  SELECT u.codusu, r.nomrol INTO v_actor, v_rol
  FROM public.usuario AS u JOIN public.rol AS r ON r.codrol = u.codrol
  WHERE u.uuidusu = auth.uid() AND u.estusu IS TRUE AND r.estrol IS TRUE
  FOR SHARE OF u, r;
  IF NOT FOUND OR v_rol NOT IN ('Gerente', 'Administradora', 'Vendedor') THEN
    RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'Rol comercial no autorizado para cancelar';
  END IF;
  IF p_codsep IS NULL OR p_codsep <= 0 OR p_idempotencia IS NULL THEN
    RAISE EXCEPTION USING ERRCODE = 'PT650', MESSAGE = 'Solicitud de cancelación inválida';
  END IF;
  v_motivo := NULLIF(pg_catalog.btrim(pg_catalog.regexp_replace(COALESCE(p_motivo, ''), '[[:space:]]+', ' ', 'g')), '');
  IF v_motivo IS NULL OR pg_catalog.char_length(v_motivo) > 250 OR v_motivo ~ '[[:cntrl:]]' THEN
    RAISE EXCEPTION USING ERRCODE = 'PT655', MESSAGE = 'El motivo es obligatorio y debe tener hasta 250 caracteres';
  END IF;
  v_observacion := NULLIF(pg_catalog.btrim(pg_catalog.regexp_replace(COALESCE(p_observacion_dinero, ''), '[[:space:]]+', ' ', 'g')), '');
  IF v_observacion IS NULL OR pg_catalog.char_length(v_observacion) > 2000 OR v_observacion ~ '[[:cntrl:]]' THEN
    RAISE EXCEPTION USING ERRCODE = 'PT656', MESSAGE = 'La observación del adelanto conservado es obligatoria y debe tener hasta 2000 caracteres';
  END IF;
  v_payload := pg_catalog.jsonb_build_object('tipo', 'Separacion', 'codsep', p_codsep::text,
    'motivo', v_motivo, 'observacionDinero', v_observacion);

  SELECT coduni INTO v_coduni FROM public.separacion WHERE codsep = p_codsep;
  IF NOT FOUND THEN
    RAISE EXCEPTION USING ERRCODE = 'PT651', MESSAGE = 'Separación inexistente';
  END IF;
  -- Orden común HU-005/HU-006: primero unidad; luego fila de operación.
  SELECT * INTO v_unidad FROM public.unidad WHERE coduni = v_coduni FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION USING ERRCODE = 'PT651', MESSAGE = 'Unidad inexistente';
  END IF;
  SELECT * INTO v_separacion FROM public.separacion WHERE codsep = p_codsep FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION USING ERRCODE = 'PT651', MESSAGE = 'Separación inexistente';
  END IF;

  IF v_rol = 'Vendedor' AND v_actor IS DISTINCT FROM v_separacion.codusuresp THEN
    RAISE EXCEPTION USING ERRCODE = 'PT652', MESSAGE = 'El vendedor no es el responsable comercial vigente de esta separación';
  END IF;
  -- La autorización usa la asignación actual ya bloqueada; incluso un replay
  -- exige que el vendedor siga siendo responsable comercial de la operación.
  SELECT * INTO v_evento FROM public.historialcancelacion WHERE idempotencia = p_idempotencia;
  IF FOUND THEN
    IF v_evento.tipoperacion <> 'Separacion' OR v_evento.codsep IS DISTINCT FROM p_codsep
      OR v_evento.codusu IS DISTINCT FROM v_actor OR v_evento.payload IS DISTINCT FROM v_payload THEN
      RAISE EXCEPTION USING ERRCODE = 'PT658', MESSAGE = 'Idempotency-Key ya fue usada con otra cancelación';
    END IF;
    RETURN v_evento.resultado || pg_catalog.jsonb_build_object('reutilizada', true);
  END IF;
  IF v_separacion.estsep = 'Convertida' THEN
    RAISE EXCEPTION USING ERRCODE = 'PT653', MESSAGE = 'La separación convertida no se puede cancelar por separado';
  END IF;
  IF v_separacion.estsep <> 'Activa' THEN
    RAISE EXCEPTION USING ERRCODE = 'PT659', MESSAGE = 'La separación ya cambió de estado';
  END IF;

  UPDATE public.separacion SET estsep = 'Cancelada', feccansep = pg_catalog.clock_timestamp(),
    motcansep = v_motivo, codusucansep = v_actor, obscancelaciondinero = v_observacion,
    idempotenciacancelacion = p_idempotencia
  WHERE codsep = p_codsep;

  IF EXISTS (SELECT 1 FROM public.venta WHERE coduni = v_coduni AND estven <> 'Cancelada') THEN
    v_estado_unidad := 'Vendida';
  ELSIF EXISTS (SELECT 1 FROM public.separacion WHERE coduni = v_coduni AND estsep = 'Activa') THEN
    v_estado_unidad := 'Separada';
  ELSE
    v_estado_unidad := 'Disponible';
  END IF;
  UPDATE public.unidad SET estcomuni = v_estado_unidad WHERE coduni = v_coduni;

  v_resultado := pg_catalog.jsonb_build_object(
    'tipoOperacion', 'Separacion', 'codsep', p_codsep::text, 'estado', 'Cancelada',
    'cancelador', v_actor::text, 'fechaCancelacion', (SELECT feccansep FROM public.separacion WHERE codsep = p_codsep),
    'motivo', v_motivo, 'observacionDinero', v_observacion,
    'estadoComercialUnidad', v_estado_unidad, 'unidadLiberada', v_estado_unidad = 'Disponible',
    'finanzasConservadas', pg_catalog.jsonb_build_object('adelanto', v_separacion.monadesep,
      'medioPago', v_separacion.metpagsep, 'totalRecibido', v_separacion.monadesep,
      'evidenciaConservada', v_separacion.rutavouchersep IS NOT NULL),
    'reutilizada', false
  );
  BEGIN
    INSERT INTO public.historialcancelacion(
      tipoperacion, codsep, accion, codusu, motivo, observaciondinero,
      estadoanterior, estadoresultante, estcomuniresultante, idempotencia, payload, resultado
    ) VALUES ('Separacion', p_codsep, 'Cancelacion', v_actor, v_motivo, v_observacion,
      'Activa', 'Cancelada', v_estado_unidad, p_idempotencia, v_payload, v_resultado);
  EXCEPTION WHEN unique_violation THEN
    RAISE EXCEPTION USING ERRCODE = 'PT658', MESSAGE = 'La solicitud de cancelación ya fue procesada';
  END;
  RETURN v_resultado;
END;
$$;

CREATE OR REPLACE FUNCTION public.hu021_cancelar_venta(
  p_codven bigint,
  p_motivo text,
  p_observacion_dinero text,
  p_idempotencia uuid
)
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
DECLARE
  v_actor bigint;
  v_rol text;
  v_coduni bigint;
  v_unidad public.unidad%ROWTYPE;
  v_venta public.venta%ROWTYPE;
  v_separacion public.separacion%ROWTYPE;
  v_evento public.historialcancelacion%ROWTYPE;
  v_motivo text;
  v_observacion text;
  v_payload jsonb;
  v_estado_unidad text;
  v_total_pagos numeric(12,2);
  v_adelanto numeric(12,2);
  v_total_recibido numeric(12,2);
  v_cantidad_pagos integer;
  v_resultado jsonb;
BEGIN
  SELECT u.codusu, r.nomrol INTO v_actor, v_rol
  FROM public.usuario AS u JOIN public.rol AS r ON r.codrol = u.codrol
  WHERE u.uuidusu = auth.uid() AND u.estusu IS TRUE AND r.estrol IS TRUE
  FOR SHARE OF u, r;
  IF NOT FOUND OR v_rol NOT IN ('Gerente', 'Administradora', 'Vendedor') THEN
    RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'Rol comercial no autorizado para cancelar';
  END IF;
  IF p_codven IS NULL OR p_codven <= 0 OR p_idempotencia IS NULL THEN
    RAISE EXCEPTION USING ERRCODE = 'PT650', MESSAGE = 'Solicitud de cancelación inválida';
  END IF;
  v_motivo := NULLIF(pg_catalog.btrim(pg_catalog.regexp_replace(COALESCE(p_motivo, ''), '[[:space:]]+', ' ', 'g')), '');
  IF v_motivo IS NULL OR pg_catalog.char_length(v_motivo) > 250 OR v_motivo ~ '[[:cntrl:]]' THEN
    RAISE EXCEPTION USING ERRCODE = 'PT655', MESSAGE = 'El motivo es obligatorio y debe tener hasta 250 caracteres';
  END IF;
  v_observacion := NULLIF(pg_catalog.btrim(pg_catalog.regexp_replace(COALESCE(p_observacion_dinero, ''), '[[:space:]]+', ' ', 'g')), '');
  IF v_observacion IS NOT NULL AND (pg_catalog.char_length(v_observacion) > 2000 OR v_observacion ~ '[[:cntrl:]]') THEN
    RAISE EXCEPTION USING ERRCODE = 'PT656', MESSAGE = 'La observación del dinero debe tener hasta 2000 caracteres';
  END IF;
  v_payload := pg_catalog.jsonb_build_object('tipo', 'Venta', 'codven', p_codven::text,
    'motivo', v_motivo, 'observacionDinero', v_observacion);

  SELECT coduni INTO v_coduni FROM public.venta WHERE codven = p_codven;
  IF NOT FOUND THEN
    RAISE EXCEPTION USING ERRCODE = 'PT651', MESSAGE = 'Venta inexistente';
  END IF;
  SELECT * INTO v_unidad FROM public.unidad WHERE coduni = v_coduni FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION USING ERRCODE = 'PT651', MESSAGE = 'Unidad inexistente';
  END IF;
  SELECT * INTO v_venta FROM public.venta WHERE codven = p_codven FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION USING ERRCODE = 'PT651', MESSAGE = 'Venta inexistente';
  END IF;
  IF v_rol = 'Vendedor' AND v_actor IS DISTINCT FROM v_venta.codusuresp THEN
    RAISE EXCEPTION USING ERRCODE = 'PT652', MESSAGE = 'El vendedor no es el responsable comercial vigente de esta venta';
  END IF;
  -- La asignación comercial actual se evalúa después del lock y antes del replay.
  SELECT * INTO v_evento FROM public.historialcancelacion WHERE idempotencia = p_idempotencia;
  IF FOUND THEN
    IF v_evento.tipoperacion <> 'Venta' OR v_evento.codven IS DISTINCT FROM p_codven
      OR v_evento.codusu IS DISTINCT FROM v_actor OR v_evento.payload IS DISTINCT FROM v_payload THEN
      RAISE EXCEPTION USING ERRCODE = 'PT658', MESSAGE = 'Idempotency-Key ya fue usada con otra cancelación';
    END IF;
    RETURN v_evento.resultado || pg_catalog.jsonb_build_object('reutilizada', true);
  END IF;
  IF v_venta.estven <> 'Registrada' THEN
    RAISE EXCEPTION USING ERRCODE = 'PT654', MESSAGE = 'La venta ya no está en estado cancelable';
  END IF;

  SELECT COALESCE(pg_catalog.sum(montopagven), 0), pg_catalog.count(*)::integer
  INTO v_total_pagos, v_cantidad_pagos FROM public.pagoventa WHERE codven = p_codven;
  SELECT * INTO v_separacion FROM public.separacion WHERE codsep = v_venta.codsep;
  v_adelanto := CASE WHEN FOUND AND v_separacion.ingconfsep IS TRUE THEN v_separacion.monadesep ELSE 0 END;
  v_total_recibido := v_total_pagos + v_adelanto;
  IF v_total_recibido > 0 AND v_observacion IS NULL THEN
    RAISE EXCEPTION USING ERRCODE = 'PT656', MESSAGE = 'La observación sobre el dinero recibido es obligatoria';
  END IF;

  UPDATE public.venta SET estven = 'Cancelada', feccanven = pg_catalog.clock_timestamp(),
    motcanven = v_motivo, codusucanven = v_actor, obscancelaciondinero = v_observacion,
    idempotenciacancelacion = p_idempotencia
  WHERE codven = p_codven;

  IF EXISTS (SELECT 1 FROM public.venta WHERE coduni = v_coduni AND estven <> 'Cancelada') THEN
    v_estado_unidad := 'Vendida';
  ELSIF EXISTS (SELECT 1 FROM public.separacion WHERE coduni = v_coduni AND estsep = 'Activa') THEN
    v_estado_unidad := 'Separada';
  ELSE
    v_estado_unidad := 'Disponible';
  END IF;
  UPDATE public.unidad SET estcomuni = v_estado_unidad WHERE coduni = v_coduni;

  v_resultado := pg_catalog.jsonb_build_object(
    'tipoOperacion', 'Venta', 'codven', p_codven::text, 'estado', 'Cancelada',
    'cancelador', v_actor::text, 'fechaCancelacion', (SELECT feccanven FROM public.venta WHERE codven = p_codven),
    'motivo', v_motivo, 'observacionDinero', v_observacion,
    'estadoComercialUnidad', v_estado_unidad, 'unidadLiberada', v_estado_unidad = 'Disponible',
    'finanzasConservadas', pg_catalog.jsonb_build_object(
      'importe', v_venta.impven, 'adelantoSeparacion', v_adelanto,
      'pagosVenta', v_total_pagos, 'cantidadPagos', v_cantidad_pagos,
      'totalRecibido', v_total_recibido,
      'saldo', CASE WHEN v_venta.impven IS NULL THEN NULL ELSE pg_catalog.round(v_venta.impven - v_total_recibido, 2) END,
      'comprobanteExternoConservado', v_venta.refcompven IS NOT NULL,
      'estadoSeparacionVinculada', v_separacion.estsep
    ),
    'reutilizada', false
  );
  BEGIN
    INSERT INTO public.historialcancelacion(
      tipoperacion, codven, accion, codusu, motivo, observaciondinero,
      estadoanterior, estadoresultante, estcomuniresultante, idempotencia, payload, resultado
    ) VALUES ('Venta', p_codven, 'Cancelacion', v_actor, v_motivo, v_observacion,
      'Registrada', 'Cancelada', v_estado_unidad, p_idempotencia, v_payload, v_resultado);
  EXCEPTION WHEN unique_violation THEN
    RAISE EXCEPTION USING ERRCODE = 'PT658', MESSAGE = 'La solicitud de cancelación ya fue procesada';
  END;
  RETURN v_resultado;
END;
$$;


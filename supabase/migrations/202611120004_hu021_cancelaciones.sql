-- Venta vigente de la unidad: ventas canceladas siguen en la consulta histórica,
-- pero nunca sustituyen a una venta activa ni se presentan como compromiso actual.
CREATE OR REPLACE FUNCTION public.hu006_venta_de_unidad(p_coduni bigint)
RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = ''
AS $$
DECLARE
  v_venta public.venta%ROWTYPE;
  v_adelanto jsonb;
BEGIN
  PERFORM 1 FROM public.hu005_perfil_comercial();
  IF p_coduni IS NULL OR p_coduni <= 0 THEN
    RAISE EXCEPTION USING ERRCODE = 'PT600', MESSAGE = 'Unidad inválida';
  END IF;
  SELECT * INTO v_venta FROM public.venta
  WHERE coduni = p_coduni AND estven IS DISTINCT FROM 'Cancelada'
  ORDER BY codven DESC LIMIT 1;
  IF NOT FOUND THEN
    RETURN NULL;
  END IF;
  IF v_venta.codsep IS NOT NULL THEN
    SELECT pg_catalog.jsonb_build_object(
      'codsep', s.codsep::text, 'monto', s.monadesep, 'fechaPago', s.fecpagsep, 'medioPago', s.metpagsep,
      'referencia', s.refsep, 'ingresoConfirmado', s.ingconfsep, 'fechaRegistro', s.fecsep)
    INTO v_adelanto
    FROM public.separacion AS s WHERE s.codsep = v_venta.codsep;
  END IF;
  RETURN public.hu006_proyectar_venta(v_venta.codven) || pg_catalog.jsonb_build_object(
    'comprador', public.hu005_proyectar_cliente(v_venta.codcli),
    'techoNombre', (SELECT t.nomtte FROM public.tipotecho AS t WHERE t.codtte = v_venta.codtteven),
    'adelantoSeparacion', v_adelanto
  );
END;
$$;
REVOKE ALL ON FUNCTION public.hu006_venta_de_unidad(bigint) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.hu006_venta_de_unidad(bigint) TO authenticated;
COMMENT ON FUNCTION public.hu006_venta_de_unidad(bigint)
  IS 'HU-006/HU-021: devuelve solo la venta vigente de una unidad; las canceladas permanecen disponibles en el listado histórico.';

-- Lectura mínima del evento de cancelación. Vendedores solo leen operaciones
-- asignadas actualmente a ellos; creador histórico no concede visibilidad.
CREATE OR REPLACE FUNCTION public.hu021_consultar_cancelacion_separacion(p_codsep bigint)
RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = ''
AS $$
DECLARE
  v_actor bigint;
  v_rol text;
  v_responsable bigint;
  v_evento public.historialcancelacion%ROWTYPE;
  v_nombre text;
BEGIN
  SELECT u.codusu, r.nomrol INTO v_actor, v_rol
  FROM public.usuario AS u JOIN public.rol AS r ON r.codrol = u.codrol
  WHERE u.uuidusu = auth.uid() AND u.estusu IS TRUE AND r.estrol IS TRUE;
  IF NOT FOUND OR v_rol NOT IN ('Gerente', 'Administradora', 'Vendedor') THEN
    RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'Rol comercial no autorizado para consultar cancelaciones';
  END IF;
  IF p_codsep IS NULL OR p_codsep <= 0 THEN
    RAISE EXCEPTION USING ERRCODE = 'PT650', MESSAGE = 'Identificador de separación inválido';
  END IF;
  SELECT s.codusuresp INTO v_responsable FROM public.separacion AS s WHERE s.codsep = p_codsep;
  IF NOT FOUND THEN
    RAISE EXCEPTION USING ERRCODE = 'PT651', MESSAGE = 'Separación inexistente';
  END IF;
  IF v_rol = 'Vendedor' AND v_actor IS DISTINCT FROM v_responsable THEN
    RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'El vendedor no es el responsable comercial vigente de esta operación';
  END IF;
  SELECT h.* INTO v_evento FROM public.historialcancelacion AS h
  WHERE h.tipoperacion = 'Separacion' AND h.codsep = p_codsep;
  IF NOT FOUND THEN RETURN NULL; END IF;
  SELECT pg_catalog.btrim(pg_catalog.concat_ws(' ', u.nomusu, u.apepatusu, u.apematusu))
  INTO v_nombre FROM public.usuario AS u WHERE u.codusu = v_evento.codusu;
  RETURN pg_catalog.jsonb_build_object(
    'tipoOperacion', v_evento.tipoperacion, 'codOperacion', v_evento.codsep::text,
    'accion', v_evento.accion, 'actor', pg_catalog.jsonb_build_object('codusu', v_evento.codusu::text, 'nombre', v_nombre),
    'fecha', v_evento.fecaccion, 'motivo', v_evento.motivo,
    'observacionFinanciera', v_evento.observaciondinero, 'estadoAnterior', v_evento.estadoanterior,
    'estadoResultante', v_evento.estadoresultante,
    'estadoComercialResultante', v_evento.estcomuniresultante
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.hu021_consultar_cancelacion_venta(p_codven bigint)
RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = ''
AS $$
DECLARE
  v_actor bigint;
  v_rol text;
  v_responsable bigint;
  v_evento public.historialcancelacion%ROWTYPE;
  v_nombre text;
BEGIN
  SELECT u.codusu, r.nomrol INTO v_actor, v_rol
  FROM public.usuario AS u JOIN public.rol AS r ON r.codrol = u.codrol
  WHERE u.uuidusu = auth.uid() AND u.estusu IS TRUE AND r.estrol IS TRUE;
  IF NOT FOUND OR v_rol NOT IN ('Gerente', 'Administradora', 'Vendedor') THEN
    RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'Rol comercial no autorizado para consultar cancelaciones';
  END IF;
  IF p_codven IS NULL OR p_codven <= 0 THEN
    RAISE EXCEPTION USING ERRCODE = 'PT650', MESSAGE = 'Identificador de venta inválido';
  END IF;
  SELECT v.codusuresp INTO v_responsable FROM public.venta AS v WHERE v.codven = p_codven;
  IF NOT FOUND THEN
    RAISE EXCEPTION USING ERRCODE = 'PT651', MESSAGE = 'Venta inexistente';
  END IF;
  IF v_rol = 'Vendedor' AND v_actor IS DISTINCT FROM v_responsable THEN
    RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'El vendedor no es el responsable comercial vigente de esta operación';
  END IF;
  SELECT h.* INTO v_evento FROM public.historialcancelacion AS h
  WHERE h.tipoperacion = 'Venta' AND h.codven = p_codven;
  IF NOT FOUND THEN RETURN NULL; END IF;
  SELECT pg_catalog.btrim(pg_catalog.concat_ws(' ', u.nomusu, u.apepatusu, u.apematusu))
  INTO v_nombre FROM public.usuario AS u WHERE u.codusu = v_evento.codusu;
  RETURN pg_catalog.jsonb_build_object(
    'tipoOperacion', v_evento.tipoperacion, 'codOperacion', v_evento.codven::text,
    'accion', v_evento.accion, 'actor', pg_catalog.jsonb_build_object('codusu', v_evento.codusu::text, 'nombre', v_nombre),
    'fecha', v_evento.fecaccion, 'motivo', v_evento.motivo,
    'observacionFinanciera', v_evento.observaciondinero, 'estadoAnterior', v_evento.estadoanterior,
    'estadoResultante', v_evento.estadoresultante,
    'estadoComercialResultante', v_evento.estcomuniresultante
  );
END;
$$;
REVOKE ALL ON FUNCTION public.hu021_consultar_cancelacion_separacion(bigint) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.hu021_consultar_cancelacion_venta(bigint) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.hu021_consultar_cancelacion_separacion(bigint) TO authenticated;
GRANT EXECUTE ON FUNCTION public.hu021_consultar_cancelacion_venta(bigint) TO authenticated;

COMMENT ON TABLE public.historialcancelacion IS
  'HU-021: auditoría append-only de cancelaciones. No se registra una devolución ni entrega.';
COMMENT ON FUNCTION public.hu021_cancelar_separacion(bigint,text,text,uuid) IS
  'Cancela una separación Activa de forma atómica; conserva dinero/evidencia y no altera datos físicos.';
COMMENT ON FUNCTION public.hu021_cancelar_venta(bigint,text,text,uuid) IS
  'Cancela una venta Registrada no entregada; conserva pagos, adelanto, comprobante y operación original.';

COMMIT;

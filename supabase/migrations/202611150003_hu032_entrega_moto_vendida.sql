-- El formulario vigente de HU-006 persiste la modalidad en un prefijo conocido
-- de obsven. Se acepta también el prefijo histórico documentado por el panel.
CREATE OR REPLACE FUNCTION public.hu032_modalidad_acordada(p_observacion text)
RETURNS text LANGUAGE sql IMMUTABLE SET search_path = '' AS $$
  SELECT CASE
    WHEN pg_catalog.lower(COALESCE(p_observacion, '')) ~
      '^(entrega pactada \(pendiente\):|entrega acordada:)[[:space:]]*se entregará armada([[:space:]]+en [^.]+)?\.'
      THEN 'Armada'
    WHEN pg_catalog.lower(COALESCE(p_observacion, '')) ~
      '^(entrega pactada \(pendiente\):|entrega acordada:)[[:space:]]*se entregará embalada([[:space:]]+en [^.]+)?\.'
      THEN 'Embalada'
    ELSE NULL
  END
$$;
REVOKE ALL ON FUNCTION public.hu032_modalidad_acordada(text) FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.hu032_proyectar_entrega(p_codven bigint)
RETURNS jsonb LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $$
  SELECT pg_catalog.jsonb_build_object(
    'codentrega', e.codentrega::text,
    'codven', e.codven::text,
    'coduni', e.coduni::text,
    'codcli', e.codcli::text,
    'modalidad', e.modalidad,
    'sedeAcordada', pg_catalog.jsonb_build_object('codsed', sa.codsed::text, 'nombre', ua.nomubi),
    'sedeEfectiva', pg_catalog.jsonb_build_object('codsed', se.codsed::text, 'nombre', ue.nomubi),
    'fecha', e.fechaentrega::text,
    'receptor', e.receptor,
    'registradoPor', pg_catalog.jsonb_build_object(
      'codusu', e.codusu::text,
      'nombre', pg_catalog.btrim(pg_catalog.concat_ws(' ', autor.nomusu, autor.apepatusu, autor.apematusu))
    ),
    'observacion', e.observacion,
    'documentosPendientes', e.documentospendientes,
    'observacionDocumentos', e.obsdocumentos,
    'referenciaGuia', e.referenciaguia,
    'decisionTecho', pg_catalog.jsonb_build_object('decision', e.decisiontecho, 'codtte', e.codtte::text),
    'estado', e.estado,
    'registradoEn', e.fecregistro
  )
  FROM public.hu032_entrega e
  JOIN public.sede sa ON sa.codsed = e.codsedacordada
  JOIN public.ubicacion ua ON ua.codubi = sa.codubi
  JOIN public.sede se ON se.codsed = e.codsedefectiva
  JOIN public.ubicacion ue ON ue.codubi = se.codubi
  JOIN public.usuario autor ON autor.codusu = e.codusu
  WHERE e.codven = p_codven
$$;
REVOKE ALL ON FUNCTION public.hu032_proyectar_entrega(bigint) FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.hu032_estado_entrega(p_codven bigint)
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  v_venta public.venta%ROWTYPE;
  v_unidad public.unidad%ROWTYPE;
  v_modalidad text;
  v_codsed_actual bigint;
  v_nombre_sede_actual text;
  v_codsed_acordada bigint;
  v_nombre_sede_acordada text;
  v_movimiento boolean;
  v_preparacion public.preparacionunidad%ROWTYPE;
  v_tiene_preparacion boolean := false;
  v_condiciones text[] := ARRAY[]::text[];
  v_estado text;
BEGIN
  SELECT * INTO v_venta FROM public.venta WHERE codven = p_codven;
  IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE = 'PT695', MESSAGE = 'Venta inexistente'; END IF;
  IF public.hu032_proyectar_entrega(p_codven) IS NOT NULL THEN
    RETURN pg_catalog.jsonb_build_object(
      'codven', v_venta.codven::text, 'coduni', v_venta.coduni::text, 'codcli', v_venta.codcli::text,
      'estadoVenta', v_venta.estven, 'estado', 'Entregada',
      'entrega', public.hu032_proyectar_entrega(p_codven), 'condicionesFaltantes', '[]'::jsonb
    );
  END IF;
  IF v_venta.estven = 'Cancelada' THEN
    RETURN pg_catalog.jsonb_build_object(
      'codven', v_venta.codven::text, 'coduni', v_venta.coduni::text, 'codcli', v_venta.codcli::text,
      'estadoVenta', v_venta.estven, 'estado', 'Venta cancelada', 'entrega', NULL,
      'condicionesFaltantes', '[]'::jsonb
    );
  END IF;
  SELECT * INTO v_unidad FROM public.unidad WHERE coduni = v_venta.coduni;
  v_modalidad := public.hu032_modalidad_acordada(v_venta.obsven);

  IF v_venta.estven IS DISTINCT FROM 'Registrada' THEN
    v_condiciones := pg_catalog.array_append(v_condiciones, 'La venta no está vigente');
  END IF;
  IF v_unidad.estcomuni IS DISTINCT FROM 'Vendida' THEN
    v_condiciones := pg_catalog.array_append(v_condiciones, 'La unidad no conserva el estado comercial Vendida');
  END IF;
  IF v_modalidad IS NULL THEN
    v_condiciones := pg_catalog.array_append(v_condiciones, 'No existe un acuerdo explícito de entrega armada o embalada');
  END IF;
  IF v_venta.dectechoven = 'Por definir' OR v_venta.dectechoven IS NULL THEN
    v_condiciones := pg_catalog.array_append(v_condiciones, 'La decisión comercial de techo está pendiente');
  END IF;
  IF v_venta.codsedentregaprevista IS NULL THEN
    v_condiciones := pg_catalog.array_append(v_condiciones, 'No se acordó una sede de entrega');
  ELSE
    SELECT s.codsed, u.nomubi
      INTO v_codsed_acordada, v_nombre_sede_acordada
    FROM public.sede s JOIN public.ubicacion u ON u.codubi = s.codubi
    WHERE s.codsed = v_venta.codsedentregaprevista AND s.estsed IS TRUE
      AND u.estubi IS TRUE AND u.tipubi = 'Sede';
    IF NOT FOUND THEN
      v_condiciones := pg_catalog.array_append(v_condiciones, 'La sede acordada no es una sede EPSA activa');
    END IF;
  END IF;
  IF v_unidad.codubi IS NULL THEN
    v_condiciones := pg_catalog.array_append(v_condiciones, 'La ubicación de la unidad no está confirmada');
  ELSE
    SELECT s.codsed, u.nomubi INTO v_codsed_actual, v_nombre_sede_actual
    FROM public.sede s JOIN public.ubicacion u ON u.codubi = s.codubi
    WHERE s.codubi = v_unidad.codubi AND s.estsed IS TRUE AND u.estubi IS TRUE AND u.tipubi = 'Sede';
    IF NOT FOUND THEN
      v_condiciones := pg_catalog.array_append(v_condiciones, 'La unidad no está en una sede EPSA válida');
    ELSE
      IF v_codsed_actual IS DISTINCT FROM v_venta.codsedentregaprevista THEN
        v_condiciones := pg_catalog.array_append(v_condiciones, 'La ubicación actual no coincide con la sede acordada');
      END IF;
    END IF;
  END IF;
  SELECT EXISTS (SELECT 1 FROM public.movimientoubicacion m
    WHERE m.coduni = v_venta.coduni AND m.estmub IN ('Pendiente', 'En transito')) INTO v_movimiento;
  IF v_movimiento THEN
    v_condiciones := pg_catalog.array_append(v_condiciones, 'La unidad tiene un movimiento físico pendiente o en tránsito');
  END IF;
  IF v_modalidad = 'Armada' THEN
    SELECT * INTO v_preparacion FROM public.preparacionunidad WHERE coduni = v_venta.coduni;
    v_tiene_preparacion := FOUND;
    IF NOT FOUND OR v_preparacion.estarmado IS DISTINCT FROM 'Terminado' THEN
      v_condiciones := pg_catalog.array_append(v_condiciones, 'El armado final no está confirmado');
    END IF;
    IF v_venta.dectechoven = 'Sin techo'
      AND v_preparacion.esttecho = 'Instalado' THEN
      v_condiciones := pg_catalog.array_append(v_condiciones,
        'La unidad conserva un techo físicamente instalado que contradice la decisión Sin techo');
    END IF;
    IF v_venta.dectechoven = 'Con techo'
      AND (v_venta.codtteven IS NULL OR v_unidad.codtte IS DISTINCT FROM v_venta.codtteven
        OR v_preparacion.esttecho IS DISTINCT FROM 'Instalado') THEN
      v_condiciones := pg_catalog.array_append(v_condiciones, 'El tipo de techo acordado no está instalado en la unidad');
    END IF;
  END IF;

  IF pg_catalog.cardinality(v_condiciones) = 0 THEN
    v_estado := CASE WHEN v_modalidad = 'Embalada' THEN 'Lista para entrega embalada' ELSE 'Lista para entrega' END;
  ELSE
    v_estado := 'Vendida pendiente de entrega';
  END IF;
  RETURN pg_catalog.jsonb_build_object(
    'codven', v_venta.codven::text, 'coduni', v_venta.coduni::text, 'codcli', v_venta.codcli::text,
    'estadoVenta', v_venta.estven, 'estado', v_estado, 'modalidadAcordada', v_modalidad,
    'sedeAcordada', CASE WHEN v_venta.codsedentregaprevista IS NULL THEN NULL ELSE
      pg_catalog.jsonb_build_object('codsed', v_venta.codsedentregaprevista::text, 'nombre', v_nombre_sede_acordada) END,
    'ubicacionActual', CASE WHEN v_unidad.codubi IS NULL THEN NULL ELSE
      pg_catalog.jsonb_build_object('codubi', v_unidad.codubi::text, 'sede', v_nombre_sede_actual) END,
    'decisionTecho', v_venta.dectechoven, 'preparacion', CASE WHEN NOT v_tiene_preparacion THEN NULL ELSE
      pg_catalog.jsonb_build_object('armado', v_preparacion.estarmado, 'techo', v_preparacion.esttecho) END,
    'entrega', NULL, 'condicionesFaltantes', pg_catalog.to_jsonb(v_condiciones)
  );
END
$$;
REVOKE ALL ON FUNCTION public.hu032_estado_entrega(bigint) FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.hu032_consultar_entrega(p_codven bigint)
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_actor bigint; v_rol text; v_venta public.venta%ROWTYPE;
BEGIN
  SELECT p.codusu, p.rol INTO v_actor, v_rol FROM public.hu005_perfil_comercial() p;
  IF v_actor IS NULL OR v_rol NOT IN ('Gerente', 'Administradora', 'Vendedor') THEN
    RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'Rol comercial no autorizado para consultar entregas';
  END IF;
  IF p_codven IS NULL OR p_codven <= 0 THEN RAISE EXCEPTION USING ERRCODE = 'PT694', MESSAGE = 'Código de venta inválido'; END IF;
  SELECT * INTO v_venta FROM public.venta WHERE codven = p_codven;
  IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE = 'PT695', MESSAGE = 'Venta inexistente'; END IF;
  IF v_rol = 'Vendedor' AND v_actor IS DISTINCT FROM v_venta.codusuresp THEN
    RAISE EXCEPTION USING ERRCODE = 'PT697', MESSAGE = 'El vendedor no es el responsable comercial vigente de esta venta';
  END IF;
  RETURN public.hu032_estado_entrega(p_codven);
END
$$;

CREATE OR REPLACE FUNCTION public.hu032_registrar_entrega(
  p_codven bigint,
  p_coduni bigint,
  p_codcli bigint,
  p_modalidad text,
  p_fecha date,
  p_receptor text,
  p_observacion text,
  p_documentos_pendientes boolean,
  p_observacion_documentos text,
  p_referencia_guia text,
  p_idempotencia uuid
)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  v_actor bigint; v_rol text; v_coduni_observada bigint; v_venta public.venta%ROWTYPE;
  v_unidad public.unidad%ROWTYPE; v_modalidad_acordada text; v_receptor text;
  v_observacion text; v_obsdocumentos text; v_referenciaguia text;
  v_payload jsonb; v_existente public.hu032_entrega%ROWTYPE;
  v_sede_acordada bigint; v_sede_actual bigint; v_decision text;
  v_preparacion public.preparacionunidad%ROWTYPE; v_resultado jsonb;
BEGIN
  SELECT p.codusu, p.rol INTO v_actor, v_rol FROM public.hu005_perfil_comercial() p;
  IF v_actor IS NULL OR v_rol NOT IN ('Gerente', 'Administradora', 'Vendedor') THEN
    RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'Rol comercial no autorizado para registrar entregas';
  END IF;
  IF p_codven IS NULL OR p_codven <= 0 OR p_coduni IS NULL OR p_coduni <= 0
    OR p_codcli IS NULL OR p_codcli <= 0 OR p_idempotencia IS NULL
    OR p_modalidad IS NULL OR p_modalidad NOT IN ('Armada', 'Embalada') OR p_fecha IS NULL
    OR p_documentos_pendientes IS NULL THEN
    RAISE EXCEPTION USING ERRCODE = 'PT694', MESSAGE = 'Los datos obligatorios de entrega no son válidos';
  END IF;
  IF p_fecha > (pg_catalog.now() AT TIME ZONE 'America/Lima')::date THEN
    RAISE EXCEPTION USING ERRCODE = 'PT694', MESSAGE = 'La fecha efectiva de entrega no puede ser futura';
  END IF;
  v_receptor := NULLIF(pg_catalog.btrim(pg_catalog.regexp_replace(COALESCE(p_receptor, ''), '[[:space:]]+', ' ', 'g')), '');
  v_observacion := NULLIF(pg_catalog.btrim(pg_catalog.regexp_replace(COALESCE(p_observacion, ''), '[[:space:]]+', ' ', 'g')), '');
  v_obsdocumentos := NULLIF(pg_catalog.btrim(pg_catalog.regexp_replace(COALESCE(p_observacion_documentos, ''), '[[:space:]]+', ' ', 'g')), '');
  v_referenciaguia := NULLIF(pg_catalog.btrim(pg_catalog.regexp_replace(COALESCE(p_referencia_guia, ''), '[[:space:]]+', ' ', 'g')), '');
  IF v_receptor IS NULL OR pg_catalog.char_length(v_receptor) > 200 OR v_receptor ~ '[[:cntrl:]]'
    OR v_observacion IS NOT NULL AND (pg_catalog.char_length(v_observacion) > 1000 OR v_observacion ~ '[[:cntrl:]]')
    OR v_obsdocumentos IS NOT NULL AND (pg_catalog.char_length(v_obsdocumentos) > 1000 OR v_obsdocumentos ~ '[[:cntrl:]]')
    OR v_referenciaguia IS NOT NULL AND (pg_catalog.char_length(v_referenciaguia) > 250 OR v_referenciaguia ~ '[[:cntrl:]]') THEN
    RAISE EXCEPTION USING ERRCODE = 'PT694', MESSAGE = 'Receptor, observación o referencia de guía no válidos';
  END IF;
  IF p_documentos_pendientes AND (v_obsdocumentos IS NULL OR v_referenciaguia IS NULL) THEN
    RAISE EXCEPTION USING ERRCODE = 'PT696', MESSAGE = 'Si tarjeta o placa quedan pendientes, registra la observación y una referencia de guía';
  END IF;
  IF NOT p_documentos_pendientes AND v_obsdocumentos IS NOT NULL THEN
    RAISE EXCEPTION USING ERRCODE = 'PT694', MESSAGE = 'La observación de documentos requiere marcar documentos pendientes';
  END IF;

  SELECT coduni INTO v_coduni_observada FROM public.venta WHERE codven = p_codven;
  IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE = 'PT695', MESSAGE = 'Venta inexistente'; END IF;
  -- Orden de locks compartido por HU-021/HU-022/HU-003: unidad y después venta.
  SELECT * INTO v_unidad FROM public.unidad WHERE coduni = v_coduni_observada FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE = 'PT695', MESSAGE = 'Unidad de la venta inexistente'; END IF;
  SELECT * INTO v_venta FROM public.venta WHERE codven = p_codven FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE = 'PT695', MESSAGE = 'Venta inexistente'; END IF;
  IF v_venta.coduni IS DISTINCT FROM v_coduni_observada THEN
    RAISE EXCEPTION USING ERRCODE = 'PT696', MESSAGE = 'La relación entre venta y unidad cambió; consulta de nuevo';
  END IF;
  IF v_rol = 'Vendedor' AND v_actor IS DISTINCT FROM v_venta.codusuresp THEN
    RAISE EXCEPTION USING ERRCODE = 'PT697', MESSAGE = 'Solo el responsable comercial vigente puede confirmar la entrega';
  END IF;

  v_payload := pg_catalog.jsonb_build_object(
    'codven', p_codven::text, 'coduni', p_coduni::text, 'codcli', p_codcli::text,
    'modalidad', p_modalidad, 'fecha', p_fecha::text, 'receptor', v_receptor,
    'observacion', v_observacion, 'documentosPendientes', p_documentos_pendientes,
    'observacionDocumentos', v_obsdocumentos, 'referenciaGuia', v_referenciaguia
  );
  SELECT * INTO v_existente FROM public.hu032_entrega WHERE idempotencia = p_idempotencia FOR UPDATE;
  IF FOUND THEN
    IF v_existente.codusu IS DISTINCT FROM v_actor OR v_existente.payload IS DISTINCT FROM v_payload THEN
      RAISE EXCEPTION USING ERRCODE = 'PT698', MESSAGE = 'Idempotency-Key ya fue usada con otra solicitud de entrega';
    END IF;
    RETURN pg_catalog.jsonb_build_object('conflicto', false, 'reutilizada', true,
      'estado', 'Entregada', 'entrega', public.hu032_proyectar_entrega(p_codven));
  END IF;
  SELECT * INTO v_existente FROM public.hu032_entrega
  WHERE codven = p_codven OR coduni = p_coduni
  ORDER BY codentrega LIMIT 1;
  IF FOUND THEN
    RETURN pg_catalog.jsonb_build_object('conflicto', true, 'reutilizada', false,
      'mensaje', 'La venta o unidad ya tiene una entrega efectiva',
      'entregaExistente', public.hu032_proyectar_entrega(v_existente.codven));
  END IF;

  IF v_venta.estven IS DISTINCT FROM 'Registrada' THEN
    RAISE EXCEPTION USING ERRCODE = 'PT696', MESSAGE = 'La venta no está vigente para registrar su entrega';
  END IF;
  IF v_venta.coduni IS DISTINCT FROM p_coduni OR v_venta.codcli IS DISTINCT FROM p_codcli THEN
    RAISE EXCEPTION USING ERRCODE = 'PT696', MESSAGE = 'La venta no corresponde al comprador y unidad indicados';
  END IF;
  IF v_unidad.estcomuni IS DISTINCT FROM 'Vendida'
    OR pg_catalog.btrim(COALESCE(v_unidad.nummotuni, '')) = ''
    OR pg_catalog.btrim(COALESCE(v_unidad.chauni, '')) = '' OR v_unidad.codmod IS NULL THEN
    RAISE EXCEPTION USING ERRCODE = 'PT696', MESSAGE = 'La unidad no conserva una venta e identificación válidas';
  END IF;
  v_modalidad_acordada := public.hu032_modalidad_acordada(v_venta.obsven);
  IF v_modalidad_acordada IS NULL OR v_modalidad_acordada IS DISTINCT FROM p_modalidad THEN
    RAISE EXCEPTION USING ERRCODE = 'PT696', MESSAGE = 'La modalidad no coincide con un acuerdo explícito de entrega de la venta';
  END IF;
  IF v_venta.dectechoven IS NULL OR v_venta.dectechoven = 'Por definir' THEN
    RAISE EXCEPTION USING ERRCODE = 'PT696', MESSAGE = 'Resuelve expresamente la decisión de techo antes de entregar';
  END IF;
  IF v_venta.dectechoven NOT IN ('Sin techo', 'Con techo') THEN
    RAISE EXCEPTION USING ERRCODE = 'PT696', MESSAGE = 'La decisión comercial de techo no es válida para entregar';
  END IF;
  IF v_venta.codsedentregaprevista IS NULL THEN
    RAISE EXCEPTION USING ERRCODE = 'PT696', MESSAGE = 'La venta no tiene una sede de entrega acordada';
  END IF;
  PERFORM 1 FROM public.sede s JOIN public.ubicacion u ON u.codubi = s.codubi
  WHERE s.codsed = v_venta.codsedentregaprevista AND s.estsed IS TRUE
    AND u.estubi IS TRUE AND u.tipubi = 'Sede' FOR SHARE OF s, u;
  IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE = 'PT696', MESSAGE = 'La sede acordada no es una sede EPSA activa'; END IF;
  SELECT s.codsed INTO v_sede_acordada FROM public.sede s
  WHERE s.codsed = v_venta.codsedentregaprevista;
  SELECT s.codsed INTO v_sede_actual FROM public.sede s JOIN public.ubicacion u ON u.codubi = s.codubi
  WHERE s.codubi = v_unidad.codubi AND s.estsed IS TRUE AND u.estubi IS TRUE AND u.tipubi = 'Sede'
  FOR SHARE OF s, u;
  IF v_sede_actual IS NULL OR v_sede_actual IS DISTINCT FROM v_sede_acordada THEN
    RAISE EXCEPTION USING ERRCODE = 'PT696', MESSAGE = 'La unidad debe estar recibida físicamente en la sede de entrega acordada';
  END IF;
  IF EXISTS (SELECT 1 FROM public.movimientoubicacion m
    WHERE m.coduni = p_coduni AND m.estmub IN ('Pendiente', 'En transito')) THEN
    RAISE EXCEPTION USING ERRCODE = 'PT696', MESSAGE = 'La unidad tiene un movimiento pendiente o en tránsito';
  END IF;

  IF p_modalidad = 'Armada' THEN
    SELECT * INTO v_preparacion FROM public.preparacionunidad WHERE coduni = p_coduni FOR SHARE;
    IF NOT FOUND OR v_preparacion.estarmado IS DISTINCT FROM 'Terminado' THEN
      RAISE EXCEPTION USING ERRCODE = 'PT696', MESSAGE = 'El armado final de la unidad no está confirmado';
    END IF;
    IF v_venta.dectechoven = 'Con techo' THEN
      IF v_venta.codtteven IS NULL OR v_unidad.codtte IS DISTINCT FROM v_venta.codtteven
        OR v_preparacion.esttecho IS DISTINCT FROM 'Instalado' THEN
        RAISE EXCEPTION USING ERRCODE = 'PT696', MESSAGE = 'El tipo de techo acordado no está instalado en la unidad';
      END IF;
    ELSIF v_venta.dectechoven = 'Sin techo'
      AND v_preparacion.esttecho = 'Instalado' THEN
      RAISE EXCEPTION USING ERRCODE = 'PT696',
        MESSAGE = 'La unidad conserva un techo físicamente instalado que contradice la decisión Sin techo';
    END IF;
  END IF;

  INSERT INTO public.hu032_entrega(
    codven, coduni, codcli, modalidad, codsedacordada, codsedefectiva, fechaentrega,
    receptor, codusu, observacion, documentospendientes, obsdocumentos, referenciaguia,
    decisiontecho, codtte, idempotencia, payload
  ) VALUES (
    p_codven, p_coduni, p_codcli, p_modalidad, v_venta.codsedentregaprevista, v_sede_actual, p_fecha,
    v_receptor, v_actor, v_observacion, p_documentos_pendientes, v_obsdocumentos, v_referenciaguia,
    v_venta.dectechoven, v_venta.codtteven, p_idempotencia, v_payload
  ) RETURNING * INTO v_existente;
  v_resultado := pg_catalog.jsonb_build_object('conflicto', false, 'reutilizada', false,
    'estado', 'Entregada', 'entrega', public.hu032_proyectar_entrega(v_existente.codven));
  RETURN v_resultado;
EXCEPTION WHEN unique_violation THEN
  SELECT * INTO v_existente FROM public.hu032_entrega WHERE idempotencia = p_idempotencia LIMIT 1;
  IF FOUND THEN
    IF v_existente.codusu IS DISTINCT FROM v_actor OR v_existente.payload IS DISTINCT FROM v_payload THEN
      RAISE EXCEPTION USING ERRCODE = 'PT698', MESSAGE = 'Idempotency-Key ya fue usada con otra solicitud de entrega';
    END IF;
    RETURN pg_catalog.jsonb_build_object('conflicto', false, 'reutilizada', true,
      'estado', 'Entregada', 'entrega', public.hu032_proyectar_entrega(v_existente.codven));
  END IF;
  SELECT * INTO v_existente FROM public.hu032_entrega WHERE codven = p_codven OR coduni = p_coduni LIMIT 1;
  IF FOUND THEN
    RETURN pg_catalog.jsonb_build_object('conflicto', true, 'reutilizada', false,
      'mensaje', 'La venta o unidad ya tiene una entrega efectiva',
      'entregaExistente', public.hu032_proyectar_entrega(v_existente.codven));
  END IF;
  RAISE;
END
$$;


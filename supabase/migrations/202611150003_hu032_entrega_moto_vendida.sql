-- HU-021 conserva la entrega efectiva al cancelar una venta y no libera la
-- unidad. No existe en HU-021 una operación persistida de retorno/devolución.
DO $hu032_integrar_hu021$
DECLARE v_def text; v_nueva text; v_firma text := 'public.hu021_cancelar_venta(bigint,text,text,uuid)';
BEGIN
  v_def := pg_catalog.pg_get_functiondef(v_firma::pg_catalog.regprocedure);
  IF pg_catalog.strpos(v_def, 'HU-032 conservar unidad entregada') = 0 THEN
    IF v_def !~ 'IF EXISTS \(SELECT 1 FROM public\.venta WHERE coduni = v_coduni AND estven <> ''Cancelada''\) THEN' THEN
      RAISE EXCEPTION 'HU-032: no se encontró el bloque de estado de unidad de hu021_cancelar_venta';
    END IF;
    v_nueva := pg_catalog.regexp_replace(
      v_def,
      'IF EXISTS \(SELECT 1 FROM public\.venta WHERE coduni = v_coduni AND estven <> ''Cancelada''\) THEN',
      'IF EXISTS (SELECT 1 FROM public.hu032_entrega WHERE codven = p_codven) THEN' || pg_catalog.chr(10)
      || '    v_estado_unidad := ''Vendida''; -- HU-032 conservar unidad entregada' || pg_catalog.chr(10)
      || '  ELSIF EXISTS (SELECT 1 FROM public.venta WHERE coduni = v_coduni AND estven <> ''Cancelada'') THEN'
    );
    IF pg_catalog.strpos(v_nueva, 'HU-032 conservar unidad entregada') = 0 THEN
      RAISE EXCEPTION 'HU-032: no se pudo insertar la guarda de entrega en hu021_cancelar_venta';
    END IF;
    v_nueva := pg_catalog.replace(v_nueva,
      '''estadoComercialUnidad'', v_estado_unidad, ''unidadLiberada'', v_estado_unidad = ''Disponible'',',
      '''estadoComercialUnidad'', v_estado_unidad, ''unidadLiberada'', v_estado_unidad = ''Disponible'', '

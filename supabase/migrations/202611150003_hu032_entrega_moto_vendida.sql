      || '''fechaEntrega'', (SELECT fechaentrega::text FROM public.hu032_entrega WHERE codven = p_codven),');
    IF pg_catalog.strpos(v_nueva, '''entregaConservada''') = 0 THEN
      RAISE EXCEPTION 'HU-032: no se pudo agregar la proyección de entrega conservada a la cancelación';
    END IF;
    EXECUTE v_nueva;
  END IF;
END
$hu032_integrar_hu021$;


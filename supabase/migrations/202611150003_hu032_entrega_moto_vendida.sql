-- HU-022 must validate delivery under the same unit/sale locks as the relation
-- correction. A preview is advisory; both write RPCs independently revalidate.
DO $hu032_integrar_hu022$
DECLARE
  v_patch record;
  v_def text;
  v_nueva text;
BEGIN
  FOR v_patch IN SELECT * FROM (VALUES
    (
      'public.hu022_validar_unidad_venta(bigint,bigint)',
      $orig1$SELECT * INTO v_venta FROM public.venta WHERE codven = p_codven;$orig1$,
      $repl1$-- HU-032 validación de entrega antes de corrección
  SELECT * INTO v_venta FROM public.venta WHERE codven = p_codven;
  IF EXISTS (SELECT 1 FROM public.hu032_entrega WHERE codven = p_codven) THEN
    RAISE EXCEPTION USING ERRCODE = 'PT700', MESSAGE = 'La operación ya tiene entrega efectiva y no puede corregirse';
  END IF;$repl1$,
      'HU-032 validación de entrega antes de corrección', false
    ),
    (
      'public.hu022_corregir_venta(bigint,bigint,bigint,integer,text,uuid)',
      $orig2$IF v_venta.estven <> 'Registrada' THEN[[:space:]]+RAISE EXCEPTION USING ERRCODE = 'PT689', MESSAGE = 'Solo se corrigen ventas Registradas';[[:space:]]+END IF;$orig2$,
      $repl2$-- HU-032 corrección individual protegida contra entrega
  IF v_venta.estven <> 'Registrada' THEN
    RAISE EXCEPTION USING ERRCODE = 'PT689', MESSAGE = 'Solo se corrigen ventas Registradas';
  END IF;
  IF EXISTS (SELECT 1 FROM public.hu032_entrega WHERE codven = p_codven) THEN
    RAISE EXCEPTION USING ERRCODE = 'PT700', MESSAGE = 'La operación ya tiene entrega efectiva y no puede corregirse';
  END IF;$repl2$,
      'HU-032 corrección individual protegida contra entrega', true
    ),
    (
      'public.hu022_intercambiar_ventas(bigint,bigint,bigint,integer,bigint,bigint,bigint,integer,text,uuid)',
      $orig3$IF v_a.estven <> 'Registrada' OR v_b.estven <> 'Registrada' THEN[[:space:]]+RAISE EXCEPTION USING ERRCODE = 'PT689', MESSAGE = 'Solo se corrigen ventas Registradas';[[:space:]]+END IF;$orig3$,
      $repl3$-- HU-032 intercambio protegido contra entrega
  IF v_a.estven <> 'Registrada' OR v_b.estven <> 'Registrada' THEN
    RAISE EXCEPTION USING ERRCODE = 'PT689', MESSAGE = 'Solo se corrigen ventas Registradas';

-- HU-032: fuente persistida de entrega efectiva. No se infiere desde venta,
-- comprobante, ubicación, movimiento o preparación; no cambia la unidad ni HU-033.
CREATE UNIQUE INDEX IF NOT EXISTS uq_hu032_venta_relacion
  ON public.venta(codven, coduni, codcli);

CREATE TABLE IF NOT EXISTS public.hu032_entrega (
  codentrega bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codven bigint NOT NULL,
  coduni bigint NOT NULL,
  codcli bigint NOT NULL,
  modalidad varchar(10) NOT NULL CHECK (modalidad IN ('Armada', 'Embalada')),
  codsedacordada bigint NOT NULL REFERENCES public.sede(codsed),
  codsedefectiva bigint NOT NULL REFERENCES public.sede(codsed),
  fechaentrega date NOT NULL,
  receptor varchar(200) NOT NULL CHECK (btrim(receptor) <> ''),
  codusu bigint NOT NULL REFERENCES public.usuario(codusu),
  observacion varchar(1000),
  documentospendientes boolean NOT NULL DEFAULT false,
  obsdocumentos varchar(1000),
  referenciaguia varchar(250),
  decisiontecho varchar(20) NOT NULL CHECK (decisiontecho IN ('Sin techo', 'Con techo')),
  codtte bigint REFERENCES public.tipotecho(codtte),
  estado varchar(20) NOT NULL DEFAULT 'Entregada' CHECK (estado = 'Entregada'),
  idempotencia uuid NOT NULL UNIQUE,
  payload jsonb NOT NULL,
  fecregistro timestamptz NOT NULL DEFAULT pg_catalog.clock_timestamp(),
  CONSTRAINT chk_hu032_entrega_venta_techo CHECK (
    (decisiontecho = 'Sin techo' AND codtte IS NULL)
    OR (decisiontecho = 'Con techo' AND codtte IS NOT NULL)
  ),
  CONSTRAINT chk_hu032_entrega_documentos CHECK (
    (documentospendientes IS FALSE AND obsdocumentos IS NULL)
    OR (documentospendientes IS TRUE AND obsdocumentos IS NOT NULL
      AND btrim(obsdocumentos) <> '' AND referenciaguia IS NOT NULL
      AND btrim(referenciaguia) <> '')
  ),
  CONSTRAINT chk_hu032_entrega_textos CHECK (
    (observacion IS NULL OR (btrim(observacion) <> '' AND char_length(observacion) <= 1000))
    AND (obsdocumentos IS NULL OR char_length(obsdocumentos) <= 1000)
    AND (referenciaguia IS NULL OR (btrim(referenciaguia) <> '' AND char_length(referenciaguia) <= 250))
  ),
  CONSTRAINT uq_hu032_entrega_venta UNIQUE (codven),
  CONSTRAINT uq_hu032_entrega_unidad UNIQUE (coduni),
  CONSTRAINT fk_hu032_entrega_relacion_venta FOREIGN KEY (codven, coduni, codcli)
    REFERENCES public.venta(codven, coduni, codcli)
);

COMMENT ON TABLE public.hu032_entrega IS
  'Hecho append-only de entrega efectiva. Una fila acredita la entrega; no se infiere de ubicación, traslado, pago o preparación.';
COMMENT ON COLUMN public.hu032_entrega.modalidad IS
  'Instantánea del acuerdo explícito de entrega ARMADA/EMBALADA codificado en el prefijo estructurado de venta.obsven.';
COMMENT ON COLUMN public.hu032_entrega.referenciaguia IS
  'Referencia textual de guía de remisión; no representa carga binaria ni sustituye trámites externos.';

CREATE INDEX IF NOT EXISTS ix_hu032_entrega_unidad_fecha
  ON public.hu032_entrega(coduni, fechaentrega DESC, codentrega DESC);

ALTER TABLE public.hu032_entrega ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.hu032_entrega FROM PUBLIC, anon, authenticated;
DO $hu032_revocar_secuencia$
DECLARE v_secuencia text;
BEGIN
  v_secuencia := pg_catalog.pg_get_serial_sequence('public.hu032_entrega', 'codentrega');
  IF v_secuencia IS NOT NULL THEN
    EXECUTE pg_catalog.format('REVOKE ALL ON SEQUENCE %s FROM PUBLIC, anon, authenticated', v_secuencia::pg_catalog.regclass);
  END IF;
END
$hu032_revocar_secuencia$;


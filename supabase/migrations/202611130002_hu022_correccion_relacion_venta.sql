CREATE OR REPLACE FUNCTION public.hu022_perfil_autorizado()
RETURNS TABLE(codusu bigint, rol text)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = '' AS $$
BEGIN
  RETURN QUERY
  SELECT u.codusu, r.nomrol::text
  FROM public.usuario AS u JOIN public.rol AS r ON r.codrol = u.codrol
  WHERE u.uuidusu = auth.uid() AND u.estusu IS TRUE AND r.estrol IS TRUE
    AND r.nomrol IN ('Gerente', 'Administradora');
  IF NOT FOUND THEN
    RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'Solo Gerente y Administradora pueden corregir relaciones';
  END IF;
END;
$$;

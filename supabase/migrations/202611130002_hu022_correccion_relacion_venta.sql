CREATE OR REPLACE FUNCTION public.hu022_validar_unidad_venta(p_codven bigint, p_coduni bigint)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  v_venta public.venta%ROWTYPE;
  v_unidad public.unidad%ROWTYPE;
  v_precio numeric;
  v_decision_techo text;
BEGIN
  SELECT * INTO v_venta FROM public.venta WHERE codven = p_codven;
  SELECT * INTO v_unidad FROM public.unidad WHERE coduni = p_coduni;
  IF NOT FOUND THEN
    RAISE EXCEPTION USING ERRCODE = 'PT681', MESSAGE = 'La unidad destino no existe';
  END IF;
  IF pg_catalog.btrim(COALESCE(v_unidad.nummotuni, '')) = ''
    OR pg_catalog.btrim(COALESCE(v_unidad.chauni, '')) = '' OR v_unidad.codmod IS NULL THEN
    RAISE EXCEPTION USING ERRCODE = 'PT691', MESSAGE = 'La unidad destino no tiene identificación suficiente';
  END IF;
  SELECT m.premod INTO v_precio FROM public.modelo AS m WHERE m.codmod = v_unidad.codmod;
  IF v_unidad.codmod IS DISTINCT FROM (SELECT u.codmod FROM public.unidad AS u WHERE u.coduni = v_venta.coduni)
    AND (v_venta.prebaseven IS NULL OR v_precio IS DISTINCT FROM v_venta.prebaseven) THEN
    RAISE EXCEPTION USING ERRCODE = 'PT688', MESSAGE = 'El modelo destino no es compatible con el precio base pactado';
  END IF;

  -- Conserva las reglas comerciales de configuración y las físicas de HU-005/HU-033.
  IF v_venta.dectechoven IN ('Sin techo', 'Con techo') AND v_unidad.codtte IS NOT NULL THEN
    SELECT public.hu005_decision_de_techo(v_unidad.codtte) INTO v_decision_techo;
    IF (v_venta.dectechoven = 'Con techo' AND v_decision_techo = 'Con techo'
        AND v_unidad.codtte IS DISTINCT FROM v_venta.codtteven)
      OR (v_venta.dectechoven = 'Sin techo' AND v_decision_techo = 'Con techo') THEN
      RAISE EXCEPTION USING ERRCODE = 'PT693', MESSAGE = 'La configuración de techo de la unidad destino contradice el acuerdo de la venta';
    END IF;
  END IF;
  PERFORM public.hu005_validar_compatibilidad_techo_instalado(
    p_coduni, v_venta.dectechoven, v_venta.codtteven);
END;
$$;
REVOKE ALL ON FUNCTION public.hu022_validar_unidad_venta(bigint,bigint) FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.hu022_proyectar_venta(p_codven bigint)
RETURNS jsonb LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $$
  SELECT pg_catalog.jsonb_build_object(
    'codven', v.codven::text,
    'versionRelacion', v.hu022_versionrelacion,
    'estado', v.estven,
    'comprador', pg_catalog.jsonb_build_object('codcli', c.codcli::text,
      'nombre', pg_catalog.btrim(pg_catalog.concat_ws(' ', c.nomcli, c.apepatcli, c.apematcli))),
    'unidad', pg_catalog.jsonb_build_object('coduni', u.coduni::text,
      'motor', u.nummotuni, 'chasis', u.chauni, 'modelo', m.nommod, 'color', u.coluni,
      'estadoComercial', u.estcomuni,
      'techoFisico', pg_catalog.jsonb_build_object('codtte', u.codtte::text, 'estado', pu.esttecho)),
    'finanzas', pg_catalog.jsonb_build_object(
      'precioBaseAcordado', v.prebaseven, 'adicionalTechoReferencial', v.adicionalrefven,
      'adicionalTechoAcordado', v.adicionalacordadoven, 'total', v.impven,
      'pagos', COALESCE((SELECT pg_catalog.count(*) FROM public.pagoventa p WHERE p.codven = v.codven), 0),
      'totalPagos', COALESCE((SELECT pg_catalog.sum(p.montopagven) FROM public.pagoventa p WHERE p.codven = v.codven), 0),
      'tienePagos', EXISTS (SELECT 1 FROM public.pagoventa p WHERE p.codven = v.codven),
      'adelantoSeparacion', CASE WHEN s.ingconfsep IS TRUE THEN s.monadesep ELSE 0 END,
      'tieneAdelanto', s.ingconfsep IS TRUE AND s.monadesep > 0,
      'totalRecibido', COALESCE((SELECT pg_catalog.sum(p.montopagven) FROM public.pagoventa p WHERE p.codven = v.codven), 0)
        + CASE WHEN s.ingconfsep IS TRUE THEN s.monadesep ELSE 0 END,
      'saldo', CASE WHEN v.impven IS NULL THEN NULL ELSE v.impven
        - COALESCE((SELECT pg_catalog.sum(p.montopagven) FROM public.pagoventa p WHERE p.codven = v.codven), 0)
        - CASE WHEN s.ingconfsep IS TRUE THEN s.monadesep ELSE 0 END END,
      'comprobanteExterno', CASE WHEN v.refcompven IS NULL THEN NULL ELSE
        pg_catalog.jsonb_build_object('referencia', v.refcompven, 'fecha', v.feccompven) END),
    'techo', pg_catalog.jsonb_build_object('decision', v.dectechoven, 'codtte', v.codtteven::text),
    'separacionVinculada', CASE WHEN s.codsep IS NULL THEN NULL ELSE pg_catalog.jsonb_build_object(
      'codsep', s.codsep::text, 'estado', s.estsep, 'codcliHistorico', s.codcli::text,
      'coduniHistorica', s.coduni::text, 'adelantoConfirmado', s.ingconfsep,
      'montoAdelanto', CASE WHEN s.ingconfsep IS TRUE THEN s.monadesep ELSE 0 END) END,
    'entrega', 'HU-032 pendiente de fuente autoritativa')
  FROM public.venta v
  JOIN public.cliente c ON c.codcli = v.codcli
  JOIN public.unidad u ON u.coduni = v.coduni
  JOIN public.modelo m ON m.codmod = u.codmod
  LEFT JOIN public.preparacionunidad pu ON pu.coduni = u.coduni
  LEFT JOIN public.separacion s ON s.codsep = v.codsep
  WHERE v.codven = p_codven
$$;
REVOKE ALL ON FUNCTION public.hu022_proyectar_venta(bigint) FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.hu022_preview_correccion_venta(p_codven bigint)
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_actor bigint; v_rol text; v_data jsonb;
BEGIN
  SELECT p.codusu, p.rol INTO v_actor, v_rol FROM public.hu022_perfil_autorizado() p;
  IF p_codven IS NULL OR p_codven <= 0 THEN
    RAISE EXCEPTION USING ERRCODE = 'PT680', MESSAGE = 'Identificador de venta inválido';
  END IF;
  SELECT public.hu022_proyectar_venta(p_codven) INTO v_data;
  IF v_data IS NULL THEN RAISE EXCEPTION USING ERRCODE = 'PT680', MESSAGE = 'Venta inexistente'; END IF;
  RETURN pg_catalog.jsonb_build_object('venta', v_data,
    'advertencias', pg_catalog.jsonb_build_array('La entrega real requiere integración con HU-032; no se infiere de ubicación ni estado comercial.'));
END;
$$;

CREATE OR REPLACE FUNCTION public.hu022_preview_intercambio_ventas(p_codven_a bigint, p_codven_b bigint)
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_a jsonb; v_b jsonb;
BEGIN
  PERFORM 1 FROM public.hu022_perfil_autorizado();
  IF p_codven_a IS NULL OR p_codven_b IS NULL OR p_codven_a <= 0 OR p_codven_b <= 0 OR p_codven_a = p_codven_b THEN
    RAISE EXCEPTION USING ERRCODE = 'PT690', MESSAGE = 'El intercambio requiere dos ventas distintas';
  END IF;
  SELECT public.hu022_proyectar_venta(p_codven_a), public.hu022_proyectar_venta(p_codven_b) INTO v_a, v_b;
  IF v_a IS NULL OR v_b IS NULL THEN RAISE EXCEPTION USING ERRCODE = 'PT680', MESSAGE = 'No se encontraron ambas ventas'; END IF;
  RETURN pg_catalog.jsonb_build_object('operaciones', pg_catalog.jsonb_build_array(v_a, v_b),
    'advertencias', pg_catalog.jsonb_build_array('La entrega real requiere integración con HU-032; no se infiere de ubicación ni estado comercial.'));
END;
$$;

CREATE OR REPLACE FUNCTION public.hu022_corregir_venta(
  p_codven bigint, p_codcli_nuevo bigint, p_coduni_nuevo bigint,
  p_version_esperada integer, p_motivo text, p_idempotencia uuid
)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  v_actor bigint; v_rol text; v_motivo text; v_payload jsonb; v_evento public.hu022_correccion_relacion%ROWTYPE;
  v_venta public.venta%ROWTYPE; v_coduni_observada bigint; v_codcli_objetivo bigint; v_coduni_objetivo bigint;
  v_cliente public.cliente%ROWTYPE; v_unidad public.unidad%ROWTYPE; v_estado_antes text; v_estado_nuevo_antes text;
  v_estado_anterior text; v_estado_nuevo text; v_version_despues integer; v_codcor bigint; v_resultado jsonb;
  v_tiene_dinero boolean;
BEGIN
  SELECT p.codusu, p.rol INTO v_actor, v_rol FROM public.hu022_perfil_autorizado() p;
  IF p_codven IS NULL OR p_codven <= 0 OR p_version_esperada IS NULL OR p_version_esperada <= 0 OR p_idempotencia IS NULL THEN
    RAISE EXCEPTION USING ERRCODE = 'PT681', MESSAGE = 'La solicitud de corrección está incompleta';
  END IF;
  v_motivo := NULLIF(pg_catalog.btrim(pg_catalog.regexp_replace(COALESCE(p_motivo, ''), '[[:space:]]+', ' ', 'g')), '');
  IF v_motivo IS NULL OR pg_catalog.char_length(v_motivo) > 500 OR v_motivo ~ '[[:cntrl:]]' THEN
    RAISE EXCEPTION USING ERRCODE = 'PT681', MESSAGE = 'El motivo es obligatorio y admite hasta 500 caracteres';
  END IF;
  v_payload := pg_catalog.jsonb_build_object('tipo', 'Individual', 'codven', p_codven::text,
    'codcliNuevo', p_codcli_nuevo::text, 'coduniNuevo', p_coduni_nuevo::text,
    'versionEsperada', p_version_esperada, 'motivo', v_motivo);
  PERFORM pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended('hu022:' || p_idempotencia::text, 22));
  SELECT * INTO v_evento FROM public.hu022_correccion_relacion WHERE idempotencia = p_idempotencia;
  IF FOUND THEN
    IF v_evento.codusu IS DISTINCT FROM v_actor OR v_evento.payload IS DISTINCT FROM v_payload THEN
      RAISE EXCEPTION USING ERRCODE = 'PT687', MESSAGE = 'Idempotency-Key ya fue usada con otra corrección';
    END IF;
    RETURN v_evento.resultado || pg_catalog.jsonb_build_object('reutilizada', true);
  END IF;

  SELECT coduni INTO v_coduni_observada FROM public.venta WHERE codven = p_codven;
  IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE = 'PT680', MESSAGE = 'Venta inexistente'; END IF;
  v_coduni_objetivo := COALESCE(p_coduni_nuevo, v_coduni_observada);
  PERFORM u.coduni FROM public.unidad u WHERE u.coduni = ANY(ARRAY[v_coduni_observada, v_coduni_objetivo])
    ORDER BY u.coduni FOR UPDATE;
  SELECT * INTO v_venta FROM public.venta WHERE codven = p_codven FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE = 'PT680', MESSAGE = 'Venta inexistente'; END IF;
  IF v_venta.coduni IS DISTINCT FROM v_coduni_observada OR v_venta.hu022_versionrelacion <> p_version_esperada THEN
    RAISE EXCEPTION USING ERRCODE = 'PT683', MESSAGE = 'La relación cambió desde la consulta; actualiza la vista antes de corregir';
  END IF;
  IF v_venta.estven <> 'Registrada' THEN RAISE EXCEPTION USING ERRCODE = 'PT689', MESSAGE = 'Solo se corrigen ventas Registradas'; END IF;
  IF v_venta.codsep IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM public.separacion s WHERE s.codsep = v_venta.codsep AND s.estsep = 'Convertida') THEN
    RAISE EXCEPTION USING ERRCODE = 'PT692', MESSAGE = 'La separación vinculada no está en estado Convertida';
  END IF;
  v_codcli_objetivo := COALESCE(p_codcli_nuevo, v_venta.codcli);
  IF v_codcli_objetivo = v_venta.codcli AND v_coduni_objetivo = v_venta.coduni THEN
    RAISE EXCEPTION USING ERRCODE = 'PT684', MESSAGE = 'La corrección no cambia comprador ni unidad';
  END IF;
  IF v_codcli_objetivo <> v_venta.codcli THEN
    SELECT * INTO v_cliente FROM public.cliente WHERE codcli = v_codcli_objetivo AND estcli IS TRUE FOR SHARE;
    IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE = 'PT682', MESSAGE = 'El comprador destino no existe o está inactivo'; END IF;
    SELECT EXISTS (SELECT 1 FROM public.pagoventa WHERE codven = p_codven)
      OR v_venta.refcompven IS NOT NULL
      OR EXISTS (SELECT 1 FROM public.separacion s WHERE s.codsep = v_venta.codsep
        AND s.ingconfsep IS TRUE AND s.monadesep > 0)
    INTO v_tiene_dinero;
    IF v_tiene_dinero AND v_rol <> 'Gerente' THEN
      RAISE EXCEPTION USING ERRCODE = 'PT686', MESSAGE = 'El cambio de comprador con dinero o comprobante requiere revisión y confirmación de Gerente';
    END IF;
  END IF;
  IF v_coduni_objetivo <> v_venta.coduni THEN
    SELECT * INTO v_unidad FROM public.unidad WHERE coduni = v_coduni_objetivo FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE = 'PT681', MESSAGE = 'La unidad destino no existe'; END IF;
    IF v_unidad.estcomuni <> 'Disponible'
      OR EXISTS (SELECT 1 FROM public.venta x WHERE x.coduni = v_coduni_objetivo AND x.estven <> 'Cancelada')
      OR EXISTS (SELECT 1 FROM public.separacion x WHERE x.coduni = v_coduni_objetivo AND x.estsep = 'Activa') THEN
      RAISE EXCEPTION USING ERRCODE = 'PT685', MESSAGE = 'La unidad destino tiene un compromiso o no está disponible';
    END IF;
    SELECT estcomuni INTO v_estado_antes FROM public.unidad WHERE coduni = v_venta.coduni;
    v_estado_nuevo_antes := v_unidad.estcomuni;
    PERFORM public.hu022_validar_unidad_venta(p_codven, v_coduni_objetivo);
  ELSE
    SELECT estcomuni INTO v_estado_antes FROM public.unidad WHERE coduni = v_venta.coduni;
    v_estado_nuevo_antes := v_estado_antes;
  END IF;

  UPDATE public.venta SET codcli = v_codcli_objetivo, coduni = v_coduni_objetivo WHERE codven = p_codven;
  IF v_coduni_objetivo <> v_venta.coduni THEN
    SELECT CASE WHEN EXISTS (SELECT 1 FROM public.venta x WHERE x.coduni = v_venta.coduni AND x.estven <> 'Cancelada') THEN 'Vendida'
      WHEN EXISTS (SELECT 1 FROM public.separacion x WHERE x.coduni = v_venta.coduni AND x.estsep = 'Activa') THEN 'Separada'
      ELSE 'Disponible' END INTO v_estado_anterior;
    UPDATE public.unidad SET estcomuni = v_estado_anterior WHERE coduni = v_venta.coduni;
    UPDATE public.unidad SET estcomuni = 'Vendida' WHERE coduni = v_coduni_objetivo;
  ELSE v_estado_anterior := v_estado_antes;
  END IF;
  SELECT estcomuni INTO v_estado_nuevo FROM public.unidad WHERE coduni = v_coduni_objetivo;
  SELECT hu022_versionrelacion INTO v_version_despues FROM public.venta WHERE codven = p_codven;
  v_codcor := pg_catalog.nextval('public.hu022_correccion_relacion_codcor_seq');
  v_resultado := pg_catalog.jsonb_build_object('codcor', v_codcor::text, 'tipo', 'Individual',
    'motivo', v_motivo, 'actor', v_actor::text, 'reutilizada', false,
    'operaciones', pg_catalog.jsonb_build_array(pg_catalog.jsonb_build_object(
      'codven', p_codven::text, 'codcliAnterior', v_venta.codcli::text, 'codcliNuevo', v_codcli_objetivo::text,
      'coduniAnterior', v_venta.coduni::text, 'coduniNueva', v_coduni_objetivo::text,
      'versionAnterior', v_venta.hu022_versionrelacion, 'versionRelacion', v_version_despues,
      'estadoUnidadAnterior', v_estado_antes, 'estadoUnidadOrigenResultante', v_estado_anterior,
      'estadoUnidadDestinoAnterior', v_estado_nuevo_antes, 'estadoUnidadResultante', v_estado_nuevo,
      'codsepVinculada', v_venta.codsep::text, 'venta', public.hu022_proyectar_venta(p_codven))));
  INSERT INTO public.hu022_correccion_relacion(codcor, tipocor, codusu, motivocor, idempotencia, payload, resultado)
  VALUES (v_codcor, 'Individual', v_actor, v_motivo, p_idempotencia, v_payload, v_resultado);
  INSERT INTO public.hu022_correccion_relacion_detalle(codcor, codven, codcli_anterior, codcli_nuevo,
    coduni_anterior, coduni_nueva, codsep, estado_unidad_anterior, estado_unidad_origen_resultante,
    estado_unidad_destino_anterior, estado_unidad_resultante,
    version_anterior, version_resultante)
  VALUES (v_codcor, p_codven, v_venta.codcli, v_codcli_objetivo, v_venta.coduni, v_coduni_objetivo,
    v_venta.codsep, v_estado_antes, v_estado_anterior, v_estado_nuevo_antes, v_estado_nuevo,
    v_venta.hu022_versionrelacion, v_version_despues);
  RETURN v_resultado;
END;
$$;

CREATE OR REPLACE FUNCTION public.hu022_intercambiar_ventas(
  p_codven_a bigint, p_codcli_a_nuevo bigint, p_coduni_a_nueva bigint, p_version_a integer,
  p_codven_b bigint, p_codcli_b_nuevo bigint, p_coduni_b_nueva bigint, p_version_b integer,
  p_motivo text, p_idempotencia uuid
)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  v_actor bigint; v_rol text; v_motivo text; v_payload jsonb; v_evento public.hu022_correccion_relacion%ROWTYPE;
  v_a public.venta%ROWTYPE; v_b public.venta%ROWTYPE; v_unidad_a public.unidad%ROWTYPE; v_unidad_b public.unidad%ROWTYPE;
  v_observada_a bigint; v_observada_b bigint; v_cli_a bigint; v_cli_b bigint; v_estado_a text; v_estado_b text;
  v_codcor bigint; v_resultado jsonb; v_tiene_dinero boolean; v_version_a_nueva integer; v_version_b_nueva integer;
BEGIN
  SELECT p.codusu, p.rol INTO v_actor, v_rol FROM public.hu022_perfil_autorizado() p;
  IF p_codven_a IS NULL OR p_codven_b IS NULL OR p_codven_a <= 0 OR p_codven_b <= 0 OR p_codven_a = p_codven_b
    OR p_version_a IS NULL OR p_version_a <= 0 OR p_version_b IS NULL OR p_version_b <= 0
    OR p_coduni_a_nueva IS NULL OR p_coduni_b_nueva IS NULL OR p_coduni_a_nueva <= 0 OR p_coduni_b_nueva <= 0
    OR p_idempotencia IS NULL THEN
    RAISE EXCEPTION USING ERRCODE = 'PT690', MESSAGE = 'El intercambio requiere dos ventas, unidades y versiones válidas';
  END IF;
  v_motivo := NULLIF(pg_catalog.btrim(pg_catalog.regexp_replace(COALESCE(p_motivo, ''), '[[:space:]]+', ' ', 'g')), '');
  IF v_motivo IS NULL OR pg_catalog.char_length(v_motivo) > 500 OR v_motivo ~ '[[:cntrl:]]' THEN
    RAISE EXCEPTION USING ERRCODE = 'PT681', MESSAGE = 'El motivo es obligatorio y admite hasta 500 caracteres';
  END IF;
  v_payload := pg_catalog.jsonb_build_object('tipo', 'Intercambio', 'motivo', v_motivo,
    'operaciones', pg_catalog.jsonb_build_array(
      pg_catalog.jsonb_build_object('codven',p_codven_a::text,'codcliNuevo',p_codcli_a_nuevo::text,
        'coduniNueva',p_coduni_a_nueva::text,'versionEsperada',p_version_a),
      pg_catalog.jsonb_build_object('codven',p_codven_b::text,'codcliNuevo',p_codcli_b_nuevo::text,
        'coduniNueva',p_coduni_b_nueva::text,'versionEsperada',p_version_b)));
  PERFORM pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended('hu022:' || p_idempotencia::text, 22));
  SELECT * INTO v_evento FROM public.hu022_correccion_relacion WHERE idempotencia = p_idempotencia;
  IF FOUND THEN
    IF v_evento.codusu IS DISTINCT FROM v_actor OR v_evento.payload IS DISTINCT FROM v_payload THEN
      RAISE EXCEPTION USING ERRCODE = 'PT687', MESSAGE = 'Idempotency-Key ya fue usada con otra corrección';
    END IF;
    RETURN v_evento.resultado || pg_catalog.jsonb_build_object('reutilizada', true);
  END IF;

  SELECT coduni INTO v_observada_a FROM public.venta WHERE codven = p_codven_a;
  SELECT coduni INTO v_observada_b FROM public.venta WHERE codven = p_codven_b;
  IF v_observada_a IS NULL OR v_observada_b IS NULL THEN RAISE EXCEPTION USING ERRCODE = 'PT680', MESSAGE = 'No se encontraron ambas ventas'; END IF;
  PERFORM u.coduni FROM public.unidad u WHERE u.coduni = ANY(ARRAY[v_observada_a,v_observada_b])
    ORDER BY u.coduni FOR UPDATE;
  PERFORM v.codven FROM public.venta v WHERE v.codven = ANY(ARRAY[p_codven_a,p_codven_b])
    ORDER BY v.codven FOR UPDATE;
  SELECT * INTO v_a FROM public.venta WHERE codven = p_codven_a;
  SELECT * INTO v_b FROM public.venta WHERE codven = p_codven_b;
  IF v_a.coduni IS DISTINCT FROM v_observada_a OR v_b.coduni IS DISTINCT FROM v_observada_b
    OR v_a.hu022_versionrelacion <> p_version_a OR v_b.hu022_versionrelacion <> p_version_b THEN
    RAISE EXCEPTION USING ERRCODE = 'PT683', MESSAGE = 'Una relación cambió desde la consulta; actualiza ambas ventas';
  END IF;
  IF v_a.estven <> 'Registrada' OR v_b.estven <> 'Registrada' THEN
    RAISE EXCEPTION USING ERRCODE = 'PT689', MESSAGE = 'Solo se corrigen ventas Registradas';
  END IF;
  IF (v_a.codsep IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM public.separacion s WHERE s.codsep=v_a.codsep AND s.estsep='Convertida'))
    OR (v_b.codsep IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM public.separacion s WHERE s.codsep=v_b.codsep AND s.estsep='Convertida')) THEN
    RAISE EXCEPTION USING ERRCODE = 'PT692', MESSAGE = 'Una separación vinculada no está en estado Convertida';
  END IF;
  IF v_observada_a = v_observada_b OR p_coduni_a_nueva <> v_observada_b OR p_coduni_b_nueva <> v_observada_a THEN
    RAISE EXCEPTION USING ERRCODE = 'PT690', MESSAGE = 'El intercambio debe reasignar exactamente las dos unidades en sentido cruzado';
  END IF;
  IF EXISTS (SELECT 1 FROM public.venta x WHERE x.coduni IN (v_observada_a,v_observada_b)
      AND x.estven <> 'Cancelada' AND x.codven NOT IN (p_codven_a,p_codven_b))
    OR EXISTS (SELECT 1 FROM public.separacion x WHERE x.coduni IN (v_observada_a,v_observada_b) AND x.estsep = 'Activa') THEN
    RAISE EXCEPTION USING ERRCODE = 'PT685', MESSAGE = 'Una unidad del intercambio tiene un tercer compromiso vigente';
  END IF;
  SELECT * INTO v_unidad_a FROM public.unidad WHERE coduni = v_observada_a;
  SELECT * INTO v_unidad_b FROM public.unidad WHERE coduni = v_observada_b;
  IF v_unidad_a.estcomuni <> 'Vendida' OR v_unidad_b.estcomuni <> 'Vendida' THEN
    RAISE EXCEPTION USING ERRCODE = 'PT685', MESSAGE = 'El estado comercial de las unidades no coincide con las ventas vigentes';
  END IF;
  v_cli_a := COALESCE(p_codcli_a_nuevo, v_a.codcli); v_cli_b := COALESCE(p_codcli_b_nuevo, v_b.codcli);
  IF v_cli_a = v_a.codcli AND v_cli_b = v_b.codcli THEN
    -- El intercambio de unidad ya es un cambio efectivo, por lo que no se requiere cambio de comprador.
    NULL;
  END IF;
  IF v_cli_a <> v_a.codcli THEN
    PERFORM 1 FROM public.cliente WHERE codcli = v_cli_a AND estcli IS TRUE FOR SHARE;
    IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE = 'PT682', MESSAGE = 'El comprador A no existe o está inactivo'; END IF;
    SELECT EXISTS (SELECT 1 FROM public.pagoventa WHERE codven = p_codven_a) OR v_a.refcompven IS NOT NULL
      OR EXISTS (SELECT 1 FROM public.separacion s WHERE s.codsep = v_a.codsep AND s.ingconfsep IS TRUE AND s.monadesep > 0)
      INTO v_tiene_dinero;
    IF v_tiene_dinero AND v_rol <> 'Gerente' THEN RAISE EXCEPTION USING ERRCODE = 'PT686', MESSAGE = 'El cambio de comprador con dinero o comprobante requiere revisión y confirmación de Gerente'; END IF;
  END IF;
  IF v_cli_b <> v_b.codcli THEN
    PERFORM 1 FROM public.cliente WHERE codcli = v_cli_b AND estcli IS TRUE FOR SHARE;
    IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE = 'PT682', MESSAGE = 'El comprador B no existe o está inactivo'; END IF;
    SELECT EXISTS (SELECT 1 FROM public.pagoventa WHERE codven = p_codven_b) OR v_b.refcompven IS NOT NULL
      OR EXISTS (SELECT 1 FROM public.separacion s WHERE s.codsep = v_b.codsep AND s.ingconfsep IS TRUE AND s.monadesep > 0)
      INTO v_tiene_dinero;
    IF v_tiene_dinero AND v_rol <> 'Gerente' THEN RAISE EXCEPTION USING ERRCODE = 'PT686', MESSAGE = 'El cambio de comprador con dinero o comprobante requiere revisión y confirmación de Gerente'; END IF;
  END IF;
  PERFORM public.hu022_validar_unidad_venta(p_codven_a, p_coduni_a_nueva);
  PERFORM public.hu022_validar_unidad_venta(p_codven_b, p_coduni_b_nueva);
  v_estado_a := v_unidad_a.estcomuni; v_estado_b := v_unidad_b.estcomuni;
  SET CONSTRAINTS ALL DEFERRED;
  UPDATE public.venta SET codcli = v_cli_a, coduni = p_coduni_a_nueva WHERE codven = p_codven_a;
  UPDATE public.venta SET codcli = v_cli_b, coduni = p_coduni_b_nueva WHERE codven = p_codven_b;
  UPDATE public.unidad SET estcomuni = 'Vendida' WHERE coduni IN (v_observada_a,v_observada_b);
  SELECT hu022_versionrelacion INTO v_version_a_nueva FROM public.venta WHERE codven = p_codven_a;
  SELECT hu022_versionrelacion INTO v_version_b_nueva FROM public.venta WHERE codven = p_codven_b;
  v_codcor := pg_catalog.nextval('public.hu022_correccion_relacion_codcor_seq');
  v_resultado := pg_catalog.jsonb_build_object('codcor',v_codcor::text,'tipo','Intercambio','motivo',v_motivo,
    'actor',v_actor::text,'reutilizada',false,'operaciones',pg_catalog.jsonb_build_array(
      pg_catalog.jsonb_build_object('codven',p_codven_a::text,'codcliAnterior',v_a.codcli::text,'codcliNuevo',v_cli_a::text,
        'coduniAnterior',v_a.coduni::text,'coduniNueva',p_coduni_a_nueva::text,'versionAnterior',v_a.hu022_versionrelacion,
        'versionRelacion',v_version_a_nueva,'estadoUnidadAnterior',v_estado_a,'estadoUnidadOrigenResultante','Vendida',
        'estadoUnidadDestinoAnterior',v_estado_b,'estadoUnidadResultante','Vendida',
        'codsepVinculada',v_a.codsep::text,'venta',public.hu022_proyectar_venta(p_codven_a)),
      pg_catalog.jsonb_build_object('codven',p_codven_b::text,'codcliAnterior',v_b.codcli::text,'codcliNuevo',v_cli_b::text,
        'coduniAnterior',v_b.coduni::text,'coduniNueva',p_coduni_b_nueva::text,'versionAnterior',v_b.hu022_versionrelacion,
        'versionRelacion',v_version_b_nueva,'estadoUnidadAnterior',v_estado_b,'estadoUnidadOrigenResultante','Vendida',
        'estadoUnidadDestinoAnterior',v_estado_a,'estadoUnidadResultante','Vendida',
        'codsepVinculada',v_b.codsep::text,'venta',public.hu022_proyectar_venta(p_codven_b))));
  INSERT INTO public.hu022_correccion_relacion(codcor,tipocor,codusu,motivocor,idempotencia,payload,resultado)
    VALUES(v_codcor,'Intercambio',v_actor,v_motivo,p_idempotencia,v_payload,v_resultado);
  INSERT INTO public.hu022_correccion_relacion_detalle(codcor,codven,codcli_anterior,codcli_nuevo,coduni_anterior,coduni_nueva,
    codsep,estado_unidad_anterior,estado_unidad_origen_resultante,estado_unidad_destino_anterior,
    estado_unidad_resultante,version_anterior,version_resultante)
  VALUES (v_codcor,p_codven_a,v_a.codcli,v_cli_a,v_a.coduni,p_coduni_a_nueva,v_a.codsep,v_estado_a,'Vendida',v_estado_b,'Vendida',v_a.hu022_versionrelacion,v_version_a_nueva),
         (v_codcor,p_codven_b,v_b.codcli,v_cli_b,v_b.coduni,p_coduni_b_nueva,v_b.codsep,v_estado_b,'Vendida',v_estado_a,'Vendida',v_b.hu022_versionrelacion,v_version_b_nueva);
  RETURN v_resultado;
END;
$$;

CREATE OR REPLACE FUNCTION public.hu022_historial_venta(p_codven bigint)
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_actor bigint; v_rol text; v_resultado jsonb;
BEGIN
  SELECT p.codusu,p.rol INTO v_actor,v_rol FROM public.hu022_perfil_autorizado() p;
  IF p_codven IS NULL OR p_codven <= 0 THEN RAISE EXCEPTION USING ERRCODE = 'PT681', MESSAGE = 'Identificador de venta inválido'; END IF;
  IF NOT EXISTS (SELECT 1 FROM public.venta WHERE codven = p_codven) THEN RAISE EXCEPTION USING ERRCODE = 'PT680', MESSAGE = 'Venta inexistente'; END IF;
  SELECT COALESCE(pg_catalog.jsonb_agg(pg_catalog.jsonb_build_object(
    'codcor',e.codcor::text,'tipo',e.tipocor,'fecha',e.feccor,'motivo',e.motivocor,
    'actor',pg_catalog.jsonb_build_object('codusu',e.codusu::text,'nombre',pg_catalog.btrim(pg_catalog.concat_ws(' ',u.nomusu,u.apepatusu,u.apematusu))),
    'operaciones', (SELECT pg_catalog.jsonb_agg(pg_catalog.jsonb_build_object(
      'codven',d.codven::text,'codcliAnterior',d.codcli_anterior::text,'codcliNuevo',d.codcli_nuevo::text,
      'coduniAnterior',d.coduni_anterior::text,'coduniNueva',d.coduni_nueva::text,'codsepVinculada',d.codsep::text,
      'estadoUnidadAnterior',d.estado_unidad_anterior,'estadoUnidadOrigenResultante',d.estado_unidad_origen_resultante,
      'estadoUnidadDestinoAnterior',d.estado_unidad_destino_anterior,'estadoUnidadResultante',d.estado_unidad_resultante,
      'versionAnterior',d.version_anterior,'versionRelacion',d.version_resultante)
      ORDER BY d.codven) FROM public.hu022_correccion_relacion_detalle d WHERE d.codcor=e.codcor)
    ) ORDER BY e.feccor DESC,e.codcor DESC), '[]'::jsonb)
  INTO v_resultado FROM public.hu022_correccion_relacion e
  JOIN public.hu022_correccion_relacion_detalle d ON d.codcor=e.codcor
  JOIN public.usuario u ON u.codusu=e.codusu WHERE d.codven=p_codven;
  RETURN v_resultado;
END;
$$;


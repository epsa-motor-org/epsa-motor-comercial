CREATE OR REPLACE FUNCTION public.hu022_versionar_relacion_venta()
RETURNS trigger LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
  IF NEW.codcli IS DISTINCT FROM OLD.codcli OR NEW.coduni IS DISTINCT FROM OLD.coduni THEN
    NEW.hu022_versionrelacion := OLD.hu022_versionrelacion + 1;
  ELSIF NEW.hu022_versionrelacion IS DISTINCT FROM OLD.hu022_versionrelacion THEN
    RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'La versión de relación solo cambia con una corrección HU-022';
  END IF;
  RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION public.hu022_versionar_relacion_venta() FROM PUBLIC, anon, authenticated;
CREATE TRIGGER hu022_version_relacion_venta
  BEFORE UPDATE ON public.venta FOR EACH ROW
  EXECUTE FUNCTION public.hu022_versionar_relacion_venta();


-- HU-022: corrección trazable del comprador/unidad de una venta registrada.
-- La constraint diferible permite intercambiar dos unidades dentro de una única
-- transacción sin exponer un estado intermedio ni liberar unidades.
ALTER TABLE public.venta
  ADD COLUMN hu022_versionrelacion integer NOT NULL DEFAULT 1,
  ADD COLUMN hu022_codunivigente bigint GENERATED ALWAYS AS
    (CASE WHEN estven <> 'Cancelada' THEN coduni ELSE NULL END) STORED,
  ADD CONSTRAINT chk_hu022_versionrelacion CHECK (hu022_versionrelacion > 0);

DROP INDEX public.uq_hu006_venta_unidad;

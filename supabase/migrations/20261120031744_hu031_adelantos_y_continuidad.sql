-- El límite/antigüedad de HU005 corresponde a dinero recibido al separar.
-- Una proyección de recibos HU031 puede incluir techo y haberse cobrado hace
-- más de 30 días. Su origen/importe los valida hu031_origen_separacion, sin
-- cambiar los controles de las separaciones ordinarias ni falsear la fecha.
CREATE OR REPLACE FUNCTION public.hu005_verificar_tope_adelanto()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE v_precio numeric;
BEGIN
 IF NEW.codpedorigen IS NOT NULL THEN RETURN NEW;END IF;
 IF NEW.monadesep<100 THEN RAISE SQLSTATE 'PT442' USING MESSAGE='El adelanto mínimo es S/ 100.00';END IF;
 SELECT m.premod INTO v_precio FROM public.unidad u JOIN public.modelo m USING(codmod) WHERE u.coduni=NEW.coduni;
 IF v_precio IS NULL OR v_precio<=0 THEN RAISE SQLSTATE 'PT436' USING MESSAGE='La moto no tiene precio de lista registrado';END IF;
 IF NEW.monadesep>v_precio THEN RAISE SQLSTATE 'PT435' USING MESSAGE='El adelanto no puede superar el precio de lista de la moto';END IF;
 IF NEW.fecpagsep<(now() AT TIME ZONE 'America/Lima')::date-30 THEN RAISE SQLSTATE 'PT437' USING MESSAGE='La fecha del adelanto no puede ser de hace más de 30 días';END IF;
 RETURN NEW;
END $$;
REVOKE ALL ON FUNCTION public.hu005_verificar_tope_adelanto() FROM PUBLIC,anon,authenticated;

CREATE OR REPLACE FUNCTION hu031_privado.acceso_evidencia(p_ruta text,p_escritura boolean)
RETURNS boolean LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path='' AS $$
DECLARE a record;x public.pedidocliente%ROWTYPE;v_id bigint;
BEGIN
  SELECT * INTO STRICT a FROM hu031_privado.actor();
  IF p_ruta IS NULL OR p_ruta!~'^pedidos/[1-9][0-9]*/[0-9a-f-]{36}\.(pdf|png|jpg|webp)$' THEN RETURN false;END IF;
  v_id:=split_part(p_ruta,'/',2)::bigint;
  SELECT * INTO x FROM public.pedidocliente WHERE codped=v_id;
  RETURN FOUND AND (a.rol<>'Vendedor' OR x.codusuresp=a.codusu)
    AND (NOT p_escritura OR x.estadoped IN ('Pendiente de unidad','Unidad propuesta'));
EXCEPTION WHEN OTHERS THEN RETURN false;
END $$;
CREATE OR REPLACE FUNCTION public.hu031_acceso_evidencia(p_ruta text,p_escritura boolean DEFAULT false)
RETURNS boolean LANGUAGE sql STABLE SECURITY INVOKER SET search_path='' AS $$ SELECT hu031_privado.acceso_evidencia(p_ruta,p_escritura) $$;
REVOKE ALL ON FUNCTION public.hu031_acceso_evidencia(text,boolean) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.hu031_acceso_evidencia(text,boolean) TO authenticated;
INSERT INTO storage.buckets(id,name,public,file_size_limit,allowed_mime_types)
VALUES('pedidos-evidencia','pedidos-evidencia',false,5242880,ARRAY['image/jpeg','image/png','image/webp','application/pdf']) ON CONFLICT(id) DO NOTHING;
DROP POLICY IF EXISTS hu031_evidencia_insertar ON storage.objects;
CREATE POLICY hu031_evidencia_insertar ON storage.objects FOR INSERT TO authenticated
  WITH CHECK(bucket_id='pedidos-evidencia' AND owner=auth.uid() AND public.hu031_acceso_evidencia(name,true));
DROP POLICY IF EXISTS hu031_evidencia_leer ON storage.objects;
CREATE POLICY hu031_evidencia_leer ON storage.objects FOR SELECT TO authenticated
  USING(bucket_id='pedidos-evidencia' AND public.hu031_acceso_evidencia(name,false));

CREATE OR REPLACE FUNCTION hu031_privado.proyectar(p_codped bigint)
RETURNS jsonb LANGUAGE sql STABLE SECURITY INVOKER SET search_path='' AS $$
 SELECT hu031_privado.proyectar_base(p_codped)||jsonb_build_object(
   'pagos',coalesce((SELECT jsonb_agg(jsonb_build_object('codpagped',pp.codpagped::text,'monto',pp.monto,'fecha',pp.fecha,'medioPago',pp.medio,
     'referencia',pp.referencia,'rutaEvidencia',pp.rutaevidencia,'observacion',pp.observacion,'autor',pp.codusu::text,'confirmadoPor',pp.codusuconfirmador::text)
     ORDER BY pp.codpagped) FROM public.pagopedidocliente pp WHERE pp.codped=p.codped),'[]'::jsonb),
   'totalRecibido',coalesce((SELECT sum(monto) FROM public.pagopedidocliente WHERE codped=p.codped),0),
   'saldoReferencial',p.preciobase+p.adicionaltecho-coalesce((SELECT sum(monto) FROM public.pagopedidocliente WHERE codped=p.codped),0),
   'operacion',jsonb_build_object('codsep',p.codsep::text,'estadoSeparacion',s.estsep,'codven',coalesce(p.codven,v.codven)::text,'estadoVenta',v.estven,
     'coduni',coalesce(v.coduni,s.coduni)::text,'venta',CASE WHEN v.codven IS NOT NULL THEN jsonb_build_object(
       'base',vf.d->'precioBaseAcordado','adicional',vf.d->'adicionalTechoAcordado','descuento',vf.d->'descuento',
       'total',vf.d->'importe','recibido',vf.d->'totalRecibido','saldo',vf.d->'saldo','techo',vf.d->'techo') END),
   'unidadPropuesta',(SELECT jsonb_build_object('coduni',u.coduni::text,'motor',u.nummotuni,'chasis',u.chauni,'color',u.coluni,'estado',u.estcomuni,
     'techoConfigurado',t.nomtte,'estadoTecho',pr.esttecho,
     'techoFisico',CASE WHEN pr.esttecho='Instalado' THEN t.nomtte END,
     'codtteFisico',CASE WHEN pr.esttecho='Instalado' THEN u.codtte::text END)
     FROM public.unidad u LEFT JOIN public.tipotecho t USING(codtte) LEFT JOIN public.preparacionunidad pr ON pr.coduni=u.coduni WHERE u.coduni=p.codunipropuesta))
 FROM public.pedidocliente p LEFT JOIN public.separacion s ON s.codsep=p.codsep
 LEFT JOIN LATERAL(SELECT vv.codven,vv.estven,vv.coduni FROM public.venta vv WHERE vv.codven=p.codven OR (p.codsep IS NOT NULL AND vv.codsep=p.codsep) ORDER BY vv.codven DESC LIMIT 1)v ON true
 LEFT JOIN LATERAL(SELECT public.hu006_proyectar_venta(v.codven) d)vf ON v.codven IS NOT NULL
 WHERE p.codped=p_codped
$$;

CREATE OR REPLACE FUNCTION hu031_privado.verificar_origen_separacion()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE p public.pedidocliente%ROWTYPE;v_monto numeric;
BEGIN
 IF TG_OP='UPDATE' AND OLD.codpedorigen IS NOT NULL THEN
   IF NEW.codpedorigen IS DISTINCT FROM OLD.codpedorigen OR NEW.monadesep IS DISTINCT FROM OLD.monadesep THEN
     RAISE SQLSTATE 'PT409' USING MESSAGE='El origen y el importe del adelanto se conservan';END IF;
   RETURN NEW;
 END IF;
 IF NEW.codpedorigen IS NULL THEN RETURN NEW;END IF;
 SELECT * INTO STRICT p FROM public.pedidocliente WHERE codped=NEW.codpedorigen;
 SELECT coalesce(sum(monto),0) INTO v_monto FROM public.pagopedidocliente WHERE codped=p.codped;
 IF NEW.monadesep IS DISTINCT FROM v_monto OR v_monto<100 OR v_monto>p.preciobase+p.adicionaltecho OR NEW.codcli<>p.codcli
   OR NEW.coduni IS DISTINCT FROM p.codunipropuesta OR NEW.metpagsep<>'Adelanto de pedido' THEN
   RAISE SQLSTATE 'PT409' USING MESSAGE='El adelanto debe conservar el pedido y sus recibos originales';END IF;
 RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS hu031_origen_separacion ON public.separacion;
CREATE TRIGGER hu031_origen_separacion BEFORE INSERT OR UPDATE OF codpedorigen,monadesep ON public.separacion
 FOR EACH ROW EXECUTE FUNCTION hu031_privado.verificar_origen_separacion();

CREATE OR REPLACE FUNCTION hu031_privado.accion(p_codped bigint,p_accion text,p_datos jsonb,p_clave uuid)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE a record;p public.pedidocliente%ROWTYPE;i public.pedidoclienteintento%ROWTYPE;
 u public.unidad%ROWTYPE;v_total numeric;v_monto numeric;v_recibido numeric;v_medio text;v_fecha date;v_ref text;v_ruta text;v_obs text;
 v_conf bigint;v_tipo bigint;v_decision text;v_extra numeric;v_base numeric;v_color text;v_mod bigint;v_codsep bigint;v_venta jsonb;v_desc numeric;
BEGIN
 SELECT * INTO STRICT a FROM hu031_privado.actor();
 IF p_clave IS NULL OR p_codped IS NULL OR p_codped<=0 OR jsonb_typeof(p_datos) IS DISTINCT FROM 'object'
   OR p_accion NOT IN ('adelanto','acuerdo','proponer','continuar','cancelar') OR p_accion IS NULL THEN
   RAISE SQLSTATE 'PT400' USING MESSAGE='Solicitud de pedido inválida';END IF;
 SELECT * INTO p FROM public.pedidocliente WHERE codped=p_codped FOR UPDATE;
 IF NOT FOUND OR (a.rol='Vendedor' AND p.codusuresp<>a.codusu) THEN RAISE SQLSTATE 'PT404' USING MESSAGE='Pedido no encontrado o fuera de tu ámbito';END IF;
 SELECT * INTO i FROM public.pedidoclienteintento WHERE codped=p_codped AND clave=p_clave;
 IF FOUND THEN
   IF i.codusu<>a.codusu OR i.accion<>p_accion OR i.payload IS DISTINCT FROM p_datos THEN RAISE SQLSTATE 'PT409' USING MESSAGE='Este intento ya se usó con otros datos';END IF;
   RETURN jsonb_build_object('pedido',hu031_privado.proyectar(p_codped),'reutilizada',true);
 END IF;
 IF p.estadoped IN ('Vinculado','Cancelado') THEN RAISE SQLSTATE 'PT409' USING MESSAGE='El pedido ya está vinculado o cancelado; consulta la operación original';END IF;
 IF (p_datos->>'versionEsperada')::integer IS DISTINCT FROM p.versionped THEN RAISE SQLSTATE 'PT409' USING MESSAGE='El pedido cambió; actualiza los datos antes de confirmar';END IF;
 SELECT coalesce(sum(monto),0) INTO v_recibido FROM public.pagopedidocliente WHERE codped=p_codped;
 v_total:=p.preciobase+p.adicionaltecho;
 IF p_accion='adelanto' THEN
   IF EXISTS(SELECT 1 FROM jsonb_object_keys(p_datos) k WHERE k NOT IN ('versionEsperada','monto','fecha','medioPago','referencia','rutaEvidencia','observacion','ingresoConfirmado','codusuConfirmador')) THEN RAISE SQLSTATE 'PT400' USING MESSAGE='Campos de adelanto no permitidos';END IF;
   v_monto:=(p_datos->>'monto')::numeric;v_fecha:=(p_datos->>'fecha')::date;v_medio:=p_datos->>'medioPago';
   v_ref:=nullif(btrim(p_datos->>'referencia'),'');v_ruta:=nullif(btrim(p_datos->>'rutaEvidencia'),'');v_obs:=nullif(btrim(p_datos->>'observacion'),'');
   IF v_monto IS NULL OR v_monto<=0 OR v_monto>99999999.99 OR v_monto<>round(v_monto,2) OR (v_recibido=0 AND v_monto<100)
     OR v_recibido+v_monto>v_total OR v_fecha IS NULL OR v_fecha> (now() AT TIME ZONE 'America/Lima')::date
     OR v_fecha<(now() AT TIME ZONE 'America/Lima')::date-30 OR (p_datos->'ingresoConfirmado') IS DISTINCT FROM 'true'::jsonb
     OR v_medio IS NULL OR v_medio NOT IN ('Efectivo','Transferencia') OR length(coalesce(v_ref,''))>200 OR length(coalesce(v_obs,''))>2000 THEN
     RAISE SQLSTATE 'PT422' USING MESSAGE='Adelanto inválido: comprueba mínimo inicial100, importe, fecha e ingreso confirmado';END IF;
   IF v_medio='Efectivo' THEN
     IF v_obs IS NULL OR v_ref IS NOT NULL OR v_ruta IS NOT NULL OR p_datos->>'codusuConfirmador' IS NOT NULL THEN RAISE SQLSTATE 'PT422' USING MESSAGE='El efectivo requiere recepción documentada y no una referencia bancaria';END IF;
     v_conf:=a.codusu;
   ELSE
     v_conf:=(p_datos->>'codusuConfirmador')::bigint;
     IF v_ref IS NULL OR v_ruta IS NULL OR NOT hu031_privado.acceso_evidencia(v_ruta,true)
       OR split_part(v_ruta,'/',2)::bigint<>p_codped
       OR NOT EXISTS(SELECT 1 FROM storage.objects WHERE bucket_id='pedidos-evidencia' AND name=v_ruta)
       OR NOT EXISTS(SELECT 1 FROM public.usuario uu JOIN public.rol r USING(codrol) WHERE uu.codusu=v_conf AND uu.estusu AND r.estrol AND r.nomrol='Gerente' AND uu.corusu NOT ILIKE '%@epsa.internal') THEN
       RAISE SQLSTATE 'PT422' USING MESSAGE='La transferencia requiere evidencia del pedido y confirmación previa del gerente';END IF;
   END IF;
   INSERT INTO public.pagopedidocliente(codped,monto,fecha,medio,referencia,rutaevidencia,observacion,codusu,codusuconfirmador,clave)
     VALUES(p_codped,v_monto,v_fecha,v_medio,v_ref,v_ruta,v_obs,a.codusu,v_conf,p_clave);
 ELSIF p_accion='acuerdo' THEN
   IF EXISTS(SELECT 1 FROM jsonb_object_keys(p_datos) k WHERE k NOT IN ('versionEsperada','codmod','color','techo','motivo','adicionalTechoAcordado')) THEN RAISE SQLSTATE 'PT400' USING MESSAGE='Campos del acuerdo no permitidos';END IF;
   v_mod:=(p_datos->>'codmod')::bigint;v_color:=nullif(btrim(p_datos->>'color'),'');v_obs:=nullif(btrim(p_datos->>'motivo'),'');
   v_decision:=p_datos->'techo'->>'decision';v_tipo:=(p_datos->'techo'->>'codtte')::bigint;
   SELECT m.premod INTO v_base FROM public.modelo m JOIN public.tipomotocar tm USING(codtmo) WHERE m.codmod=v_mod AND tm.esttmo AND m.premod>0;
   IF NOT FOUND OR v_obs IS NULL OR length(v_obs)>500 OR length(coalesce(v_color,''))>50 OR v_decision IS NULL OR v_decision NOT IN ('Por definir','Sin techo','Con techo') THEN RAISE SQLSTATE 'PT422' USING MESSAGE='Acuerdo comercial incompleto';END IF;
   v_extra:=0;
   IF v_decision='Con techo' THEN SELECT adicionalref INTO v_extra FROM public.tipotecho WHERE codtte=v_tipo AND esttte AND lower(btrim(nomtte))<>'sin techo';
     IF NOT FOUND OR v_extra IS NULL THEN RAISE SQLSTATE 'PT422' USING MESSAGE='Tipo de techo no disponible';END IF;
   ELSIF v_tipo IS NOT NULL THEN RAISE SQLSTATE 'PT400' USING MESSAGE='El tipo solo corresponde a Con techo';END IF;
   IF p_datos->>'adicionalTechoAcordado' IS NOT NULL THEN
     v_extra:=(p_datos->>'adicionalTechoAcordado')::numeric;
     IF v_extra<0 OR v_extra>99999999.99 OR v_extra<>round(v_extra,2) OR (v_decision<>'Con techo' AND v_extra<>0) THEN RAISE SQLSTATE 'PT422' USING MESSAGE='Adicional de techo acordado inválido';END IF;
   END IF;
   IF v_base+v_extra<v_recibido THEN RAISE SQLSTATE 'PT422' USING MESSAGE='El nuevo acuerdo no puede ser inferior al dinero recibido';END IF;
   UPDATE public.pedidocliente SET codmod=v_mod,color=v_color,decisiontecho=v_decision,codtte=v_tipo,preciobase=v_base,adicionaltecho=v_extra,
     codunipropuesta=NULL,estadoped='Pendiente de unidad' WHERE codped=p_codped;
 ELSIF p_accion IN ('proponer','continuar') THEN
   IF p_accion='proponer' AND EXISTS(SELECT 1 FROM jsonb_object_keys(p_datos) k WHERE k NOT IN ('versionEsperada','coduni','adecuacionAceptada')) THEN RAISE SQLSTATE 'PT400' USING MESSAGE='Campos de unidad no permitidos';END IF;
   IF p_accion='continuar' AND EXISTS(SELECT 1 FROM jsonb_object_keys(p_datos) k WHERE k NOT IN ('versionEsperada','destino','modalidad','adecuacionAceptada','descuento','motivoDescuento','codusuAutorizadorDescuento','confirmacionTelefonicaRecibida')) THEN RAISE SQLSTATE 'PT400' USING MESSAGE='Campos de continuidad no permitidos';END IF;
   SELECT * INTO u FROM public.unidad WHERE coduni=CASE WHEN p_accion='proponer' THEN (p_datos->>'coduni')::bigint ELSE p.codunipropuesta END FOR UPDATE;
   IF NOT FOUND OR nullif(btrim(u.nummotuni),'') IS NULL OR nullif(btrim(u.chauni),'') IS NULL THEN RAISE SQLSTATE 'PT422' USING MESSAGE='Selecciona una unidad real identificada';END IF;
   IF u.codmod<>p.codmod OR (p.color IS NOT NULL AND lower(btrim(u.coluni)) IS DISTINCT FROM lower(p.color)) THEN RAISE SQLSTATE 'PT422' USING MESSAGE='Modelo o color diferentes: actualiza expresamente el acuerdo antes de vincular';END IF;
   IF u.estcomuni<>'Disponible' OR EXISTS(SELECT 1 FROM public.separacion WHERE coduni=u.coduni AND estsep='Activa')
     OR EXISTS(SELECT 1 FROM public.venta WHERE coduni=u.coduni AND estven='Registrada') THEN RAISE SQLSTATE 'PT409' USING MESSAGE='La unidad ya no está libre; selecciona otra';END IF;
   IF u.codtte IS NOT NULL AND (p.decisiontecho<>'Con techo' OR p.codtte IS DISTINCT FROM u.codtte)
     AND p_datos->'adecuacionAceptada' IS DISTINCT FROM 'true'::jsonb THEN RAISE SQLSTATE 'PT422' USING MESSAGE='Confirma la diferencia entre techo físico y acordado; la adecuación seguirá pendiente';END IF;
   IF p_accion='proponer' THEN
     UPDATE public.pedidocliente SET codunipropuesta=u.coduni,estadoped='Unidad propuesta' WHERE codped=p_codped;
   ELSE
     IF p_datos->>'destino' IS NULL OR p_datos->>'destino' NOT IN ('Separacion','Venta') THEN RAISE SQLSTATE 'PT400' USING MESSAGE='Elige separación o venta';END IF;
     IF (SELECT premod FROM public.modelo WHERE codmod=p.codmod) IS DISTINCT FROM p.preciobase THEN RAISE SQLSTATE 'PT409' USING MESSAGE='El precio actual del modelo cambió; revisa y actualiza expresamente el acuerdo';END IF;
     IF a.rol='Vendedor' AND p.codusuresp<>a.codusu THEN RAISE SQLSTATE 'PT403' USING MESSAGE='Responsable comercial no autorizado';END IF;
     IF NOT EXISTS(SELECT 1 FROM public.usuario uu JOIN public.rol r USING(codrol) WHERE uu.codusu=p.codusuresp AND uu.estusu AND r.estrol AND r.nomrol IN ('Gerente','Administradora','Vendedor')) THEN RAISE SQLSTATE 'PT422' USING MESSAGE='Responsable comercial inactivo';END IF;
     IF NOT EXISTS(SELECT 1 FROM public.cliente WHERE codcli=p.codcli AND estcli) THEN RAISE SQLSTATE 'PT422' USING MESSAGE='Comprador inactivo';END IF;
     IF v_recibido>0 THEN
       -- Proyección única del dinero original, con recibos y medios en el pedido.
       INSERT INTO public.separacion(coduni,codcli,codusu,codusuresp,monadesep,fecpagsep,metpagsep,refsep,obssep,
         ingconfsep,codusuconfsep,fecconfsep,idempotenciasep,estsep,dectechosep,codttesep,fecdectechosep,codusudectechosep,codpedorigen)
       SELECT u.coduni,p.codcli,a.codusu,p.codusuresp,v_recibido,min(pp.fecha),'Adelanto de pedido','Pedido '||p_codped,
         'Adelanto original del pedido; no es un nuevo cobro. Consultar sus recibos.',true,a.codusu,now(),p_clave,'Activa',
         p.decisiontecho,p.codtte,now(),a.codusu,p_codped FROM public.pagopedidocliente pp WHERE pp.codped=p_codped
       RETURNING codsep INTO v_codsep;
       UPDATE public.unidad SET estcomuni='Separada' WHERE coduni=u.coduni;
     ELSIF p_datos->>'destino'='Separacion' THEN RAISE SQLSTATE 'PT422' USING MESSAGE='Sin adelanto no hay separación; conserva la propuesta o registra una venta válida';END IF;
     IF p_datos->>'destino'='Venta' THEN
       IF p_datos->>'modalidad' IS NULL OR p_datos->>'modalidad' NOT IN ('Contado','Crédito') THEN RAISE SQLSTATE 'PT400' USING MESSAGE='Modalidad de venta inválida';END IF;
       v_desc:=coalesce((p_datos->>'descuento')::numeric,0);
       v_venta:=public.hu006_crear_venta_http(u.coduni,p.codcli,p.codusuresp,p.codsedatencion,
         (now() AT TIME ZONE 'America/Lima')::date,p_datos->>'modalidad',p.adicionaltecho,p.codsedentregaprevista,
         '[]'::jsonb,jsonb_strip_nulls(jsonb_build_object('decision',p.decisiontecho,'codtte',p.codtte)),NULL,NULL,
         'Continuación del pedido '||p_codped||'. '||coalesce(p.observacion,''),p_clave,v_desc,p_datos->>'motivoDescuento',
         (p_datos->>'codusuAutorizadorDescuento')::bigint,coalesce((p_datos->>'confirmacionTelefonicaRecibida')::boolean,false));
     END IF;
     UPDATE public.pedidocliente SET estadoped='Vinculado',codsep=v_codsep,codven=(v_venta->>'codven')::bigint WHERE codped=p_codped;
   END IF;
 ELSE
   IF EXISTS(SELECT 1 FROM jsonb_object_keys(p_datos) k WHERE k NOT IN ('versionEsperada','motivo','observacionDinero'))
     OR nullif(btrim(p_datos->>'motivo'),'') IS NULL OR length(p_datos->>'motivo')>500
     OR (v_recibido>0 AND nullif(btrim(p_datos->>'observacionDinero'),'') IS NULL) THEN RAISE SQLSTATE 'PT422' USING MESSAGE='Registra motivo y tratamiento conocido del dinero; no se ejecutará un reembolso';END IF;
   UPDATE public.pedidocliente SET estadoped='Cancelado' WHERE codped=p_codped;
 END IF;
 UPDATE public.pedidocliente SET versionped=versionped+1,actualizadoen=clock_timestamp() WHERE codped=p_codped;
 INSERT INTO public.pedidoclienteevento(codped,codusu,tipo,detalle) VALUES(p_codped,a.codusu,p_accion,
   jsonb_build_object('antes',jsonb_build_object('modelo',p.codmod,'color',p.color,'techo',p.decisiontecho,'tipo',p.codtte,'unidad',p.codunipropuesta),
     'solicitud',p_datos,'recibidoConservado',CASE WHEN p_accion='adelanto' THEN v_recibido+v_monto ELSE v_recibido END));

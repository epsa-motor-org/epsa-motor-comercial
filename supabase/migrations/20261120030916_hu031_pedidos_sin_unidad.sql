BEGIN;

-- HU-031: pedido comercial independiente de una unidad, venta o ingreso físico.
-- Las funciones privilegiadas viven en un esquema NO expuesto; las RPC públicas
-- son SECURITY INVOKER y toda entrada resuelve identidad/permisos en PostgreSQL.
CREATE SCHEMA IF NOT EXISTS hu031_privado;
REVOKE ALL ON SCHEMA hu031_privado FROM PUBLIC, anon, authenticated;
GRANT USAGE ON SCHEMA hu031_privado TO authenticated;

CREATE TABLE IF NOT EXISTS public.pedidocliente (
  codped bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codcli bigint NOT NULL REFERENCES public.cliente(codcli),
  codmod bigint NOT NULL REFERENCES public.modelo(codmod),
  codusu bigint NOT NULL REFERENCES public.usuario(codusu),
  codusuresp bigint NOT NULL REFERENCES public.usuario(codusu),
  codsedatencion bigint NOT NULL REFERENCES public.sede(codsed),
  codsedentregaprevista bigint REFERENCES public.sede(codsed),
  color varchar(50),
  decisiontecho text NOT NULL CHECK (decisiontecho IN ('Por definir','Sin techo','Con techo')),
  codtte bigint REFERENCES public.tipotecho(codtte),
  preciobase numeric(12,2) NOT NULL CHECK (preciobase > 0),
  adicionaltecho numeric(12,2) NOT NULL CHECK (adicionaltecho >= 0),
  fechaprevista date,
  observacion varchar(2000),
  estadoped text NOT NULL DEFAULT 'Pendiente de unidad'
    CHECK (estadoped IN ('Pendiente de unidad','Unidad propuesta','Vinculado','Cancelado')),
  codunipropuesta bigint REFERENCES public.unidad(coduni),
  codsep bigint REFERENCES public.separacion(codsep),
  codven bigint REFERENCES public.venta(codven),
  versionped integer NOT NULL DEFAULT 1 CHECK (versionped > 0),
  creadoen timestamptz NOT NULL DEFAULT now(),
  actualizadoen timestamptz NOT NULL DEFAULT now(),
  idempotencia uuid NOT NULL,
  payloadinicial jsonb NOT NULL,
  CONSTRAINT hu031_techo_coherente CHECK (
    (decisiontecho = 'Con techo' AND codtte IS NOT NULL)
    OR (decisiontecho <> 'Con techo' AND codtte IS NULL AND adicionaltecho = 0)),
  CONSTRAINT hu031_pedido_idempotente UNIQUE (codusu,idempotencia)
);
CREATE INDEX IF NOT EXISTS hu031_pedido_responsable ON public.pedidocliente(codusuresp,codped DESC);
CREATE INDEX IF NOT EXISTS hu031_pedido_estado ON public.pedidocliente(estadoped,codped DESC);
CREATE INDEX IF NOT EXISTS hu031_pedido_cliente ON public.pedidocliente(codcli);
CREATE INDEX IF NOT EXISTS hu031_pedido_modelo ON public.pedidocliente(codmod);
CREATE INDEX IF NOT EXISTS hu031_pedido_atencion ON public.pedidocliente(codsedatencion);
CREATE INDEX IF NOT EXISTS hu031_pedido_entrega ON public.pedidocliente(codsedentregaprevista);
CREATE INDEX IF NOT EXISTS hu031_pedido_techo ON public.pedidocliente(codtte);
CREATE INDEX IF NOT EXISTS hu031_pedido_unidad ON public.pedidocliente(codunipropuesta);
CREATE INDEX IF NOT EXISTS hu031_pedido_separacion ON public.pedidocliente(codsep);
CREATE INDEX IF NOT EXISTS hu031_pedido_venta ON public.pedidocliente(codven);
CREATE TABLE IF NOT EXISTS public.pedidoclienteevento (
  codevento bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codped bigint NOT NULL REFERENCES public.pedidocliente(codped),
  codusu bigint NOT NULL REFERENCES public.usuario(codusu),
  fecha timestamptz NOT NULL DEFAULT now(),
  tipo text NOT NULL,
  detalle jsonb NOT NULL
);
CREATE INDEX IF NOT EXISTS hu031_evento_pedido ON public.pedidoclienteevento(codped,codevento);
CREATE INDEX IF NOT EXISTS hu031_evento_actor ON public.pedidoclienteevento(codusu);
ALTER TABLE public.pedidocliente ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pedidoclienteevento ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.pedidocliente,public.pedidoclienteevento FROM PUBLIC,anon,authenticated;
REVOKE ALL ON SEQUENCE public.pedidocliente_codped_seq,public.pedidoclienteevento_codevento_seq FROM PUBLIC,anon,authenticated;

CREATE OR REPLACE FUNCTION hu031_privado.actor()
RETURNS TABLE(codusu bigint,rol text)
LANGUAGE plpgsql STABLE SECURITY INVOKER SET search_path = '' AS $$
BEGIN
  IF auth.uid() IS NULL THEN RAISE SQLSTATE 'PT403' USING MESSAGE='Sesión comercial requerida'; END IF;
  RETURN QUERY SELECT p.codusu,p.rol FROM public.hu005_perfil_comercial() p;
END $$;

CREATE OR REPLACE FUNCTION hu031_privado.proyectar_base(p_codped bigint)
RETURNS jsonb LANGUAGE sql STABLE SECURITY INVOKER SET search_path = '' AS $$
  SELECT jsonb_build_object(
    'codped',p.codped::text,'estado',p.estadoped,'version',p.versionped,
    'creadoEn',p.creadoen,'actualizadoEn',p.actualizadoen,
    'comprador',jsonb_build_object('codcli',c.codcli::text,'nombre',concat_ws(' ',c.nomcli,c.apepatcli,c.apematcli),'telefono',c.telcli),
    'modelo',jsonb_build_object('codmod',m.codmod::text,'nombre',m.nommod),
    'color',p.color,'creador',p.codusu::text,
    'responsable',jsonb_build_object('codusu',u.codusu::text,'nombre',concat_ws(' ',u.nomusu,u.apepatusu,u.apematusu)),
    'sedeAtencion',jsonb_build_object('codsed',s.codsed::text,'nombre',ub.nomubi),
    'codsedEntregaPrevista',p.codsedentregaprevista::text,
    'techo',jsonb_build_object('decision',p.decisiontecho,'codtte',p.codtte::text,'nombre',t.nomtte),
    'precioReferencia',jsonb_build_object('base',p.preciobase,'adicional',p.adicionaltecho,'total',p.preciobase+p.adicionaltecho),
    'fechaEntregaPrevista',p.fechaprevista,'observacion',p.observacion,
    'coduniPropuesta',p.codunipropuesta::text,'codsep',p.codsep::text,'codven',p.codven::text,
    'historial',(SELECT coalesce(jsonb_agg(jsonb_build_object('id',e.codevento::text,'tipo',e.tipo,'fecha',e.fecha,'autor',e.codusu::text,
      'autorNombre',(SELECT concat_ws(' ',eu.nomusu,eu.apepatusu,eu.apematusu) FROM public.usuario eu WHERE eu.codusu=e.codusu),'detalle',e.detalle) ORDER BY e.codevento),'[]'::jsonb)
      FROM public.pedidoclienteevento e WHERE e.codped=p.codped))
  FROM public.pedidocliente p JOIN public.cliente c USING(codcli) JOIN public.modelo m USING(codmod)
  JOIN public.usuario u ON u.codusu=p.codusuresp
  JOIN public.sede s ON s.codsed=p.codsedatencion JOIN public.ubicacion ub ON ub.codubi=s.codubi
  LEFT JOIN public.tipotecho t ON t.codtte=p.codtte WHERE p.codped=p_codped
$$;

CREATE OR REPLACE FUNCTION hu031_privado.proyectar(p_codped bigint)
RETURNS jsonb LANGUAGE sql STABLE SECURITY INVOKER SET search_path='' AS $$
  SELECT hu031_privado.proyectar_base(p_codped)
$$;

CREATE OR REPLACE FUNCTION hu031_privado.formulario()
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_actor record;
BEGIN
  SELECT * INTO STRICT v_actor FROM hu031_privado.actor();
  RETURN public.hu005_formulario_separacion() || jsonb_build_object(
    'modelos',(SELECT coalesce(jsonb_agg(jsonb_build_object('codmod',m.codmod::text,'nombre',m.nommod,'precio',m.premod) ORDER BY m.nommod,m.codmod),'[]'::jsonb)
      FROM public.modelo m JOIN public.tipomotocar tm USING(codtmo) WHERE tm.esttmo AND m.premod>0),
    'sedes',(SELECT coalesce(jsonb_agg(jsonb_build_object('codsed',s.codsed::text,'nombre',u.nomubi) ORDER BY u.nomubi),'[]'::jsonb)
      FROM public.sede s JOIN public.ubicacion u USING(codubi) WHERE s.estsed AND u.estubi AND u.tipubi='Sede'));
END $$;

CREATE OR REPLACE FUNCTION hu031_privado.crear(p_datos jsonb,p_clave uuid)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE a record; x public.pedidocliente%ROWTYPE; v_id bigint; v_base numeric; v_extra numeric:=0;
  v_cli bigint;v_mod bigint;v_resp bigint;v_sede bigint;v_entrega bigint;v_tipo bigint;
  v_color text;v_obs text;v_decision text;v_fecha date;
BEGIN
  SELECT * INTO STRICT a FROM hu031_privado.actor();
  IF p_clave IS NULL OR jsonb_typeof(p_datos) IS DISTINCT FROM 'object' THEN
    RAISE SQLSTATE 'PT400' USING MESSAGE='Pedido o clave de intento inválidos'; END IF;
  IF EXISTS(SELECT 1 FROM jsonb_object_keys(p_datos) k WHERE k NOT IN
    ('codcli','codmod','codusuResponsable','codsedAtencion','codsedEntregaPrevista','color','techo','fechaEntregaPrevista','observacion')) THEN
    RAISE SQLSTATE 'PT400' USING MESSAGE='El pedido contiene campos no permitidos'; END IF;
  PERFORM pg_advisory_xact_lock(hashtextextended('HU031:'||a.codusu||':'||p_clave,31));
  SELECT * INTO x FROM public.pedidocliente WHERE codusu=a.codusu AND idempotencia=p_clave;
  IF FOUND THEN
    IF x.payloadinicial IS DISTINCT FROM p_datos THEN RAISE SQLSTATE 'PT409' USING MESSAGE='Este intento ya se usó con otros datos'; END IF;
    RETURN jsonb_build_object('pedido',hu031_privado.proyectar(x.codped),'reutilizada',true);
  END IF;
  v_cli:=(p_datos->>'codcli')::bigint;v_mod:=(p_datos->>'codmod')::bigint;
  v_resp:=(p_datos->>'codusuResponsable')::bigint;v_sede:=(p_datos->>'codsedAtencion')::bigint;
  v_entrega:=(p_datos->>'codsedEntregaPrevista')::bigint;
  v_color:=nullif(btrim(p_datos->>'color'),'');v_obs:=nullif(btrim(p_datos->>'observacion'),'');
  v_fecha:=(p_datos->>'fechaEntregaPrevista')::date;
  v_decision:=p_datos->'techo'->>'decision';v_tipo:=(p_datos->'techo'->>'codtte')::bigint;
  IF v_cli IS NULL OR v_mod IS NULL OR v_resp IS NULL OR v_sede IS NULL
    OR char_length(coalesce(v_color,''))>50 OR char_length(coalesce(v_obs,''))>2000
    OR coalesce(v_color,'')~'[[:cntrl:]]' OR coalesce(v_obs,'')~'[[:cntrl:]]' THEN
    RAISE SQLSTATE 'PT400' USING MESSAGE='Faltan datos válidos del pedido'; END IF;
  IF NOT EXISTS(SELECT 1 FROM public.cliente WHERE codcli=v_cli AND estcli AND nullif(btrim(nomcli),'') IS NOT NULL) THEN
    RAISE SQLSTATE 'PT422' USING MESSAGE='El comprador no existe o está inactivo'; END IF;
  SELECT m.premod INTO v_base FROM public.modelo m JOIN public.tipomotocar tm USING(codtmo) WHERE m.codmod=v_mod AND tm.esttmo AND m.premod>0;
  IF NOT FOUND THEN RAISE SQLSTATE 'PT422' USING MESSAGE='El modelo no tiene una referencia comercial válida'; END IF;
  IF a.rol='Vendedor' AND v_resp<>a.codusu THEN RAISE SQLSTATE 'PT403' USING MESSAGE='El vendedor debe ser responsable de su pedido'; END IF;
  IF NOT EXISTS(SELECT 1 FROM public.usuario u JOIN public.rol r USING(codrol) WHERE u.codusu=v_resp AND u.estusu AND r.estrol
    AND r.nomrol IN ('Gerente','Administradora','Vendedor') AND u.corusu NOT ILIKE '%@epsa.internal') THEN
    RAISE SQLSTATE 'PT422' USING MESSAGE='Responsable no autorizado o inactivo'; END IF;
  IF NOT EXISTS(SELECT 1 FROM public.sede s JOIN public.ubicacion u USING(codubi) WHERE s.codsed=v_sede AND s.estsed AND u.estubi AND u.tipubi='Sede')
    OR (v_entrega IS NOT NULL AND NOT EXISTS(SELECT 1 FROM public.sede s JOIN public.ubicacion u USING(codubi) WHERE s.codsed=v_entrega AND s.estsed AND u.estubi AND u.tipubi='Sede')) THEN
    RAISE SQLSTATE 'PT422' USING MESSAGE='La atención y entrega previstas requieren una sede EPSA activa'; END IF;
  IF v_decision IS NULL OR v_decision NOT IN ('Por definir','Sin techo','Con techo')
    OR (v_decision<>'Con techo' AND v_tipo IS NOT NULL) THEN RAISE SQLSTATE 'PT400' USING MESSAGE='Elección de techo inválida'; END IF;
  IF v_decision='Con techo' THEN
    SELECT adicionalref INTO v_extra FROM public.tipotecho WHERE codtte=v_tipo AND esttte AND lower(btrim(nomtte))<>'sin techo';
    IF NOT FOUND OR v_extra IS NULL OR v_extra<0 THEN RAISE SQLSTATE 'PT422' USING MESSAGE='Tipo de techo no disponible'; END IF;
  END IF;
  INSERT INTO public.pedidocliente(codcli,codmod,codusu,codusuresp,codsedatencion,codsedentregaprevista,color,decisiontecho,codtte,
    preciobase,adicionaltecho,fechaprevista,observacion,idempotencia,payloadinicial)
  VALUES(v_cli,v_mod,a.codusu,v_resp,v_sede,v_entrega,v_color,v_decision,v_tipo,v_base,v_extra,v_fecha,v_obs,p_clave,p_datos)
  RETURNING codped INTO v_id;
  INSERT INTO public.pedidoclienteevento(codped,codusu,tipo,detalle) VALUES(v_id,a.codusu,'Pedido creado',
    jsonb_build_object('techo',p_datos->'techo','unidad',null,'stockModificado',false));
  RETURN jsonb_build_object('pedido',hu031_privado.proyectar(v_id),'reutilizada',false);
EXCEPTION WHEN invalid_text_representation OR numeric_value_out_of_range OR datetime_field_overflow THEN
  RAISE SQLSTATE 'PT400' USING MESSAGE='Formato de datos del pedido inválido';
END $$;

CREATE OR REPLACE FUNCTION hu031_privado.consultar(p_codped bigint,p_limite integer,p_offset integer,p_buscar text)
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = '' AS $$
DECLARE a record;v_total bigint;v_items jsonb;
BEGIN
  SELECT * INTO STRICT a FROM hu031_privado.actor();
  IF p_codped IS NOT NULL THEN
    IF NOT EXISTS(SELECT 1 FROM public.pedidocliente WHERE codped=p_codped AND (a.rol<>'Vendedor' OR codusuresp=a.codusu)) THEN
      RAISE SQLSTATE 'PT404' USING MESSAGE='Pedido no encontrado o fuera de tu ámbito'; END IF;
    RETURN hu031_privado.proyectar(p_codped);
  END IF;
  IF p_limite IS NULL OR p_limite NOT BETWEEN 1 AND 50 OR p_offset IS NULL OR p_offset<0 OR length(coalesce(p_buscar,''))>100 THEN
    RAISE SQLSTATE 'PT400' USING MESSAGE='Filtros del pedido inválidos'; END IF;
  SELECT count(*) INTO v_total FROM public.pedidocliente p JOIN public.cliente c USING(codcli)
    WHERE (a.rol<>'Vendedor' OR p.codusuresp=a.codusu)
    AND (nullif(btrim(p_buscar),'') IS NULL OR position(lower(btrim(p_buscar)) IN lower(concat_ws(' ',p.codped,c.nomcli,c.apepatcli,c.apematcli,c.telcli)))>0);
  SELECT coalesce(jsonb_agg(hu031_privado.proyectar(q.codped) ORDER BY q.codped DESC),'[]'::jsonb) INTO v_items FROM (
    SELECT p.codped FROM public.pedidocliente p JOIN public.cliente c USING(codcli)
    WHERE (a.rol<>'Vendedor' OR p.codusuresp=a.codusu)
    AND (nullif(btrim(p_buscar),'') IS NULL OR position(lower(btrim(p_buscar)) IN lower(concat_ws(' ',p.codped,c.nomcli,c.apepatcli,c.apematcli,c.telcli)))>0)
    ORDER BY p.codped DESC LIMIT p_limite OFFSET p_offset) q;
  RETURN jsonb_build_object('items',v_items,'total',v_total,'limite',p_limite,'offset',p_offset);
END $$;

CREATE OR REPLACE FUNCTION hu031_privado.buscar_compradores(p_buscar text)
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path='' AS $$
BEGIN
 PERFORM hu031_privado.actor();
 IF p_buscar IS NULL OR length(btrim(p_buscar)) NOT BETWEEN 2 AND 100 THEN RAISE SQLSTATE 'PT400' USING MESSAGE='Busca por al menos dos caracteres de nombre o celular';END IF;
 RETURN (SELECT coalesce(jsonb_agg(to_jsonb(c)),'[]'::jsonb) FROM (
   SELECT codcli::text,nombres, "apellidoPaterno", "apellidoMaterno",telefono FROM (
     SELECT cc.codcli,cc.nomcli nombres,cc.apepatcli "apellidoPaterno",cc.apematcli "apellidoMaterno",cc.telcli telefono
     FROM public.cliente cc WHERE cc.estcli AND position(lower(btrim(p_buscar)) IN lower(concat_ws(' ',cc.nomcli,cc.apepatcli,cc.apematcli,cc.telcli)))>0
     ORDER BY cc.codcli DESC LIMIT 10) q) c);
END $$;
CREATE OR REPLACE FUNCTION public.hu031_buscar_compradores(p_buscar text) RETURNS jsonb LANGUAGE sql STABLE SECURITY INVOKER SET search_path='' AS $$ SELECT hu031_privado.buscar_compradores(p_buscar) $$;
REVOKE ALL ON FUNCTION public.hu031_buscar_compradores(text) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.hu031_buscar_compradores(text) TO authenticated;
CREATE OR REPLACE FUNCTION public.hu031_formulario() RETURNS jsonb LANGUAGE sql STABLE SECURITY INVOKER SET search_path='' AS $$ SELECT hu031_privado.formulario() $$;
CREATE OR REPLACE FUNCTION public.hu031_crear_pedido(p_datos jsonb,p_clave uuid) RETURNS jsonb LANGUAGE sql SECURITY INVOKER SET search_path='' AS $$ SELECT hu031_privado.crear(p_datos,p_clave) $$;
CREATE OR REPLACE FUNCTION public.hu031_consultar_pedidos(p_codped bigint DEFAULT NULL,p_limite integer DEFAULT 25,p_offset integer DEFAULT 0,p_buscar text DEFAULT NULL)
RETURNS jsonb LANGUAGE sql STABLE SECURITY INVOKER SET search_path='' AS $$ SELECT hu031_privado.consultar(p_codped,p_limite,p_offset,p_buscar) $$;

REVOKE ALL ON ALL FUNCTIONS IN SCHEMA hu031_privado FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION hu031_privado.buscar_compradores(text),hu031_privado.formulario(),hu031_privado.crear(jsonb,uuid),hu031_privado.consultar(bigint,integer,integer,text) TO authenticated;
REVOKE ALL ON FUNCTION public.hu031_formulario(),public.hu031_crear_pedido(jsonb,uuid),public.hu031_consultar_pedidos(bigint,integer,integer,text) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.hu031_formulario(),public.hu031_crear_pedido(jsonb,uuid),public.hu031_consultar_pedidos(bigint,integer,integer,text) TO authenticated;
COMMENT ON TABLE public.pedidocliente IS 'Pedido comercial HU-031 sin unidad obligatoria. Una propuesta no reserva stock; no equivale a compra, venta o entrega.';
NOTIFY pgrst,'reload schema';
COMMIT;

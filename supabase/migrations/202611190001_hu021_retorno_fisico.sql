BEGIN;

-- HU-032 originally allowed only one delivery per motorcycle. Keep the
-- one-delivery-per-sale rule, but preserve delivery history across resale.
ALTER TABLE public.hu032_entrega
  DROP CONSTRAINT IF EXISTS uq_hu032_entrega_unidad;

CREATE UNIQUE INDEX IF NOT EXISTS uq_hu032_entrega_id_venta_unidad
  ON public.hu032_entrega(codentrega, codven, coduni);

CREATE TABLE IF NOT EXISTS public.hu021_retorno (
  codretorno bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codven bigint NOT NULL REFERENCES public.venta(codven) ON DELETE RESTRICT,
  coduni bigint NOT NULL REFERENCES public.unidad(coduni) ON DELETE RESTRICT,
  codentrega bigint NOT NULL,
  fecharetorno date NOT NULL,
  codubi bigint NOT NULL REFERENCES public.ubicacion(codubi) ON DELETE RESTRICT,
  condicion varchar(500) NOT NULL CHECK (btrim(condicion) <> ''),
  observacion varchar(1000) NOT NULL CHECK (btrim(observacion) <> ''),
  codusu bigint NOT NULL REFERENCES public.usuario(codusu) ON DELETE RESTRICT,
  fecregistro timestamptz NOT NULL DEFAULT pg_catalog.clock_timestamp(),
  estcomuniresultante varchar(20) NOT NULL
    CHECK (estcomuniresultante IN ('Disponible', 'Separada', 'Vendida')),
  idempotencia uuid NOT NULL UNIQUE,
  payload jsonb NOT NULL,
  CONSTRAINT uq_hu021_retorno_venta UNIQUE (codven),
  CONSTRAINT fk_hu021_retorno_entrega FOREIGN KEY (codentrega, codven, coduni)
    REFERENCES public.hu032_entrega(codentrega, codven, coduni) ON DELETE RESTRICT
);

COMMENT ON TABLE public.hu021_retorno IS
  'HU-021: hecho append-only del retorno físico de una unidad después de cancelar una venta entregada.';
COMMENT ON COLUMN public.hu021_retorno.estcomuniresultante IS
  'Snapshot comercial al registrar el retorno; la condición física no crea por sí sola un bloqueo comercial.';

CREATE INDEX IF NOT EXISTS ix_hu021_retorno_unidad_fecha
  ON public.hu021_retorno(coduni, fecharetorno DESC, codretorno DESC);

ALTER TABLE public.hu021_retorno ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.hu021_retorno FROM PUBLIC, anon, authenticated;
DO $hu021_retorno_secuencia$
DECLARE v_secuencia text;
BEGIN
  v_secuencia := pg_catalog.pg_get_serial_sequence('public.hu021_retorno', 'codretorno');
  IF v_secuencia IS NOT NULL THEN
    EXECUTE pg_catalog.format('REVOKE ALL ON SEQUENCE %s FROM PUBLIC, anon, authenticated', v_secuencia::pg_catalog.regclass);
  END IF;
END
$hu021_retorno_secuencia$;

CREATE OR REPLACE FUNCTION public.hu021_impedir_edicion_retorno()
RETURNS trigger LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
  RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'El registro de retorno es inmutable';
END
$$;
REVOKE ALL ON FUNCTION public.hu021_impedir_edicion_retorno() FROM PUBLIC, anon, authenticated;
DROP TRIGGER IF EXISTS hu021_retorno_inmutable ON public.hu021_retorno;
CREATE TRIGGER hu021_retorno_inmutable
BEFORE UPDATE OR DELETE ON public.hu021_retorno
FOR EACH ROW EXECUTE FUNCTION public.hu021_impedir_edicion_retorno();

CREATE OR REPLACE FUNCTION public.hu021_proyectar_retorno(p_codven bigint)
RETURNS jsonb
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = ''
AS $$
  SELECT pg_catalog.jsonb_build_object(
    'codretorno', r.codretorno::text,
    'codven', r.codven::text,
    'coduni', r.coduni::text,
    'codentrega', r.codentrega::text,
    'fechaRetorno', r.fecharetorno::text,
    'ubicacion', pg_catalog.jsonb_build_object(
      'codubi', ub.codubi::text, 'nombre', ub.nomubi, 'tipo', ub.tipubi
    ),
    'condicion', r.condicion,
    'observacion', r.observacion,
    'registradoPor', pg_catalog.jsonb_build_object(
      'codusu', r.codusu::text,
      'nombre', pg_catalog.btrim(pg_catalog.concat_ws(' ', autor.nomusu, autor.apepatusu, autor.apematusu))
    ),
    'registradoEn', r.fecregistro,
    'estadoComercialResultante', r.estcomuniresultante
  )
  FROM public.hu021_retorno r
  JOIN public.ubicacion ub ON ub.codubi = r.codubi
  JOIN public.usuario autor ON autor.codusu = r.codusu
  WHERE r.codven = p_codven
$$;
REVOKE ALL ON FUNCTION public.hu021_proyectar_retorno(bigint) FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.hu021_registrar_retorno(
  p_codven bigint,
  p_fecharetorno date,
  p_codubi bigint,
  p_condicion text,
  p_observacion text,
  p_idempotencia uuid
)
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
DECLARE
  v_actor bigint;
  v_rol text;
  v_coduni_observada bigint;
  v_venta public.venta%ROWTYPE;
  v_unidad public.unidad%ROWTYPE;
  v_entrega public.hu032_entrega%ROWTYPE;
  v_existente public.hu021_retorno%ROWTYPE;
  v_condicion text;
  v_observacion text;
  v_payload jsonb;
  v_estado text;
  v_codubi_elegible bigint;
  v_resultado jsonb;
  v_reutilizada boolean := false;
BEGIN
  SELECT p.codusu, p.rol INTO v_actor, v_rol FROM public.hu005_perfil_comercial() p;
  IF v_actor IS NULL OR v_rol IS DISTINCT FROM 'Gerente' THEN
    RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'Solo Gerente puede registrar el retorno físico';
  END IF;
  IF p_codven IS NULL OR p_codven <= 0 OR p_fecharetorno IS NULL
    OR p_codubi IS NULL OR p_codubi <= 0 OR p_idempotencia IS NULL THEN
    RAISE EXCEPTION USING ERRCODE = 'PT701', MESSAGE = 'Los datos obligatorios del retorno no son válidos';
  END IF;
  v_condicion := NULLIF(pg_catalog.btrim(pg_catalog.regexp_replace(COALESCE(p_condicion, ''), '[[:space:]]+', ' ', 'g')), '');
  v_observacion := NULLIF(pg_catalog.btrim(pg_catalog.regexp_replace(COALESCE(p_observacion, ''), '[[:space:]]+', ' ', 'g')), '');
  IF v_condicion IS NULL OR pg_catalog.char_length(v_condicion) > 500 OR v_condicion ~ '[[:cntrl:]]'
    OR v_observacion IS NULL OR pg_catalog.char_length(v_observacion) > 1000 OR v_observacion ~ '[[:cntrl:]]'
    OR p_fecharetorno > (pg_catalog.now() AT TIME ZONE 'America/Lima')::date THEN
    RAISE EXCEPTION USING ERRCODE = 'PT701', MESSAGE = 'Fecha, condición u observación del retorno no válidas';
  END IF;

  SELECT v.coduni INTO v_coduni_observada FROM public.venta v WHERE v.codven = p_codven;
  IF NOT FOUND THEN
    RAISE EXCEPTION USING ERRCODE = 'PT702', MESSAGE = 'Venta inexistente';
  END IF;
  -- Keep the same lock order as HU-005/HU-006/HU-021/HU-032: unit, then sale.
  SELECT * INTO v_unidad FROM public.unidad WHERE coduni = v_coduni_observada FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION USING ERRCODE = 'PT702', MESSAGE = 'Unidad de la venta inexistente';
  END IF;
  SELECT * INTO v_venta FROM public.venta WHERE codven = p_codven FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION USING ERRCODE = 'PT702', MESSAGE = 'Venta inexistente';
  END IF;
  IF v_venta.coduni IS DISTINCT FROM v_coduni_observada THEN
    RAISE EXCEPTION USING ERRCODE = 'PT703', MESSAGE = 'La relación de venta cambió; consulta de nuevo';
  END IF;
  IF v_venta.estven IS DISTINCT FROM 'Cancelada' THEN
    RAISE EXCEPTION USING ERRCODE = 'PT703', MESSAGE = 'Solo se puede retornar una venta cancelada';
  END IF;

  SELECT * INTO v_entrega FROM public.hu032_entrega
  WHERE codven = p_codven AND coduni = v_venta.coduni FOR SHARE;
  IF NOT FOUND THEN
    RAISE EXCEPTION USING ERRCODE = 'PT703', MESSAGE = 'La venta cancelada no tiene una entrega efectiva HU-032';
  END IF;
  IF p_fecharetorno < v_entrega.fechaentrega THEN
    RAISE EXCEPTION USING ERRCODE = 'PT701', MESSAGE = 'La fecha de retorno no puede ser anterior a la entrega';
  END IF;

  v_payload := pg_catalog.jsonb_build_object(
    'codven', p_codven::text, 'fechaRetorno', p_fecharetorno::text,
    'codubi', p_codubi::text, 'condicion', v_condicion, 'observacion', v_observacion
  );
  SELECT * INTO v_existente FROM public.hu021_retorno
  WHERE idempotencia = p_idempotencia FOR UPDATE;
  IF FOUND THEN
    IF v_existente.codusu IS DISTINCT FROM v_actor OR v_existente.payload IS DISTINCT FROM v_payload THEN
      RAISE EXCEPTION USING ERRCODE = 'PT704', MESSAGE = 'Idempotency-Key ya fue usada con otra solicitud de retorno';
    END IF;
    v_reutilizada := true;
  ELSE
    SELECT * INTO v_existente FROM public.hu021_retorno WHERE codven = p_codven FOR UPDATE;
    IF FOUND THEN
      RAISE EXCEPTION USING ERRCODE = 'PT705', MESSAGE = 'El retorno físico de esta venta ya fue registrado';
    END IF;

    SELECT ub.codubi INTO v_codubi_elegible
    FROM public.ubicacion ub
    WHERE ub.codubi = p_codubi AND ub.estubi IS TRUE AND ub.tipubi IN ('Sede', 'Almacen')
    FOR SHARE OF ub;
    IF v_codubi_elegible IS NULL THEN
      RAISE EXCEPTION USING ERRCODE = 'PT701', MESSAGE = 'La ubicación debe existir, estar activa y ser una sede o almacén EPSA';
    END IF;

    IF EXISTS (SELECT 1 FROM public.venta x
      WHERE x.coduni = v_venta.coduni AND x.codven <> p_codven AND x.estven <> 'Cancelada') THEN
      v_estado := 'Vendida';
    ELSIF EXISTS (SELECT 1 FROM public.separacion x
      WHERE x.coduni = v_venta.coduni AND x.estsep = 'Activa') THEN
      v_estado := 'Separada';
    ELSE
      v_estado := 'Disponible';
    END IF;

    INSERT INTO public.hu021_retorno(
      codven, coduni, codentrega, fecharetorno, codubi, condicion, observacion,
      codusu, estcomuniresultante, idempotencia, payload
    ) VALUES (
      p_codven, v_venta.coduni, v_entrega.codentrega, p_fecharetorno, p_codubi,
      v_condicion, v_observacion, v_actor, v_estado, p_idempotencia, v_payload
    ) RETURNING * INTO v_existente;
    UPDATE public.unidad SET codubi = p_codubi, estcomuni = v_estado WHERE coduni = v_venta.coduni;
  END IF;

  SELECT * INTO v_unidad FROM public.unidad WHERE coduni = v_venta.coduni;
  v_resultado := pg_catalog.jsonb_build_object(
    'estado', 'Retornada',
    'venta', pg_catalog.jsonb_build_object('codven', p_codven::text, 'estado', v_venta.estven),
    'entrega', public.hu032_proyectar_entrega(p_codven),
    'retorno', public.hu021_proyectar_retorno(p_codven),
    'ubicacionActual', CASE WHEN v_unidad.codubi IS NULL THEN NULL ELSE (
      SELECT pg_catalog.jsonb_build_object('codubi', ub.codubi::text, 'nombre', ub.nomubi, 'tipo', ub.tipubi)
      FROM public.ubicacion ub WHERE ub.codubi = v_unidad.codubi
    ) END,
    'estadoComercialUnidad', v_unidad.estcomuni,
    'reutilizada', v_reutilizada
  );
  RETURN v_resultado;
EXCEPTION WHEN unique_violation THEN
  SELECT * INTO v_existente FROM public.hu021_retorno WHERE idempotencia = p_idempotencia LIMIT 1;
  IF FOUND THEN
    IF v_existente.codusu IS DISTINCT FROM v_actor OR v_existente.payload IS DISTINCT FROM v_payload THEN
      RAISE EXCEPTION USING ERRCODE = 'PT704', MESSAGE = 'Idempotency-Key ya fue usada con otra solicitud de retorno';
    END IF;
    SELECT * INTO v_venta FROM public.venta WHERE codven = p_codven;
    SELECT * INTO v_unidad FROM public.unidad WHERE coduni = v_venta.coduni;
    RETURN pg_catalog.jsonb_build_object(
      'estado', 'Retornada',
      'venta', pg_catalog.jsonb_build_object('codven', p_codven::text, 'estado', v_venta.estven),
      'entrega', public.hu032_proyectar_entrega(p_codven),
      'retorno', public.hu021_proyectar_retorno(p_codven),
      'ubicacionActual', CASE WHEN v_unidad.codubi IS NULL THEN NULL ELSE (
        SELECT pg_catalog.jsonb_build_object('codubi', ub.codubi::text, 'nombre', ub.nomubi, 'tipo', ub.tipubi)
        FROM public.ubicacion ub WHERE ub.codubi = v_unidad.codubi
      ) END,
      'estadoComercialUnidad', v_unidad.estcomuni,
      'reutilizada', true
    );
  END IF;
  IF EXISTS (SELECT 1 FROM public.hu021_retorno WHERE codven = p_codven) THEN
    RAISE EXCEPTION USING ERRCODE = 'PT705', MESSAGE = 'El retorno físico de esta venta ya fue registrado';
  END IF;
  RAISE;
END
$$;

REVOKE ALL ON FUNCTION public.hu021_registrar_retorno(bigint,date,bigint,text,text,uuid) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.hu021_registrar_retorno(bigint,date,bigint,text,text,uuid) TO authenticated;
COMMENT ON FUNCTION public.hu021_registrar_retorno(bigint,date,bigint,text,text,uuid)
  IS 'HU-021: registra atómicamente el retorno físico de una venta cancelada con entrega HU-032; conserva todo el historial previo.';

-- Reuse HU-032's status/read contract and retain the delivery as a historical
-- event, while making the return and current unit state visible after return.
DO $hu021_proyeccion_entrega_retorno$
DECLARE
  v_def text;
  v_needle text := 'IF public.hu032_proyectar_entrega(p_codven) IS NOT NULL THEN';
  v_bloque text := $bloque$
  IF public.hu032_proyectar_entrega(p_codven) IS NOT NULL
    AND EXISTS (SELECT 1 FROM public.hu021_retorno WHERE codven = p_codven) THEN
    RETURN pg_catalog.jsonb_build_object(
      'codven', v_venta.codven::text, 'coduni', v_venta.coduni::text, 'codcli', v_venta.codcli::text,
      'estadoVenta', v_venta.estven, 'estado', 'Retornada',
      'entrega', public.hu032_proyectar_entrega(p_codven),
      'retorno', public.hu021_proyectar_retorno(p_codven),
      'ubicacionActual', (SELECT pg_catalog.jsonb_build_object(
        'codubi', ub.codubi::text, 'nombre', ub.nomubi, 'tipo', ub.tipubi)
        FROM public.unidad u JOIN public.ubicacion ub ON ub.codubi = u.codubi
        WHERE u.coduni = v_venta.coduni),
      'estadoComercialUnidad', (SELECT estcomuni FROM public.unidad WHERE coduni = v_venta.coduni),
      'condicionesFaltantes', '[]'::jsonb
    );
  END IF;
$bloque$;
BEGIN
  v_def := pg_catalog.pg_get_functiondef('public.hu032_estado_entrega(bigint)'::pg_catalog.regprocedure);
  IF pg_catalog.strpos(v_def, '''Retornada''') = 0 THEN
    IF pg_catalog.strpos(v_def, v_needle) = 0 THEN
      RAISE EXCEPTION 'HU-021 retorno: no se encontró la rama vigente de hu032_estado_entrega';
    END IF;
    v_def := pg_catalog.replace(v_def, v_needle, v_bloque || v_needle);
    IF pg_catalog.strpos(v_def, '''Retornada''') = 0 THEN
      RAISE EXCEPTION 'HU-021 retorno: no se pudo insertar la proyección de retorno en hu032_estado_entrega';
    END IF;
    EXECUTE v_def;
  END IF;
END
$hu021_proyeccion_entrega_retorno$;

-- Allow HU-032 delivery history to be projected through the cancellation view.
DO $hu021_consulta_cancelacion_retorno$
DECLARE
  v_def text;
  v_needle text := '''estadoComercialResultante'', v_evento.estcomuniresultante';
  v_extra text := '''estadoComercialResultante'', v_evento.estcomuniresultante, '
    || '''entrega'', public.hu032_proyectar_entrega(p_codven), '
    || '''retorno'', public.hu021_proyectar_retorno(p_codven), '
    || '''estadoComercialUnidad'', (SELECT estcomuni FROM public.unidad WHERE coduni = (SELECT coduni FROM public.venta WHERE codven = p_codven)), '
    || '''ubicacionActual'', (SELECT pg_catalog.jsonb_build_object(''codubi'', ub.codubi::text, ''nombre'', ub.nomubi, ''tipo'', ub.tipubi) '
    || 'FROM public.unidad u JOIN public.ubicacion ub ON ub.codubi = u.codubi WHERE u.coduni = (SELECT coduni FROM public.venta WHERE codven = p_codven))';
BEGIN
  v_def := pg_catalog.pg_get_functiondef('public.hu021_consultar_cancelacion_venta(bigint)'::pg_catalog.regprocedure);
  IF pg_catalog.strpos(v_def, '''retorno'', public.hu021_proyectar_retorno(p_codven)') = 0 THEN
    IF pg_catalog.strpos(v_def, v_needle) = 0 THEN
      RAISE EXCEPTION 'HU-021 retorno: no se encontró el bloque de respuesta de hu021_consultar_cancelacion_venta';
    END IF;
    v_def := pg_catalog.replace(v_def, v_needle, v_extra);
    IF pg_catalog.strpos(v_def, '''retorno'', public.hu021_proyectar_retorno(p_codven)') = 0 THEN
      RAISE EXCEPTION 'HU-021 retorno: no se pudo agregar la proyección a la consulta de cancelación';
    END IF;
    EXECUTE v_def;
  END IF;
END
$hu021_consulta_cancelacion_retorno$;

-- HU-032's duplicate checks must be per sale, not per unit, so an already
-- returned motorcycle can be sold and delivered again without deleting history.
DO $hu032_permitir_reentrega$
DECLARE
  v_def text;
  v_needle text := 'WHERE codven = p_codven OR coduni = p_coduni';
BEGIN
  v_def := pg_catalog.pg_get_functiondef(
    'public.hu032_registrar_entrega(bigint,bigint,bigint,text,date,text,text,boolean,text,text,uuid)'::pg_catalog.regprocedure
  );
  IF pg_catalog.strpos(v_def, 'OR coduni = p_coduni') > 0 THEN
    IF pg_catalog.strpos(v_def, v_needle) = 0 THEN
      RAISE EXCEPTION 'HU-021 retorno: se detectó una guarda de unidad con formato no esperado en hu032_registrar_entrega';
    END IF;
    v_def := pg_catalog.replace(v_def, v_needle, 'WHERE codven = p_codven');
    IF pg_catalog.strpos(v_def, 'OR coduni = p_coduni') > 0 THEN
      RAISE EXCEPTION 'HU-021 retorno: no se pudieron retirar todas las guardas de entrega por unidad';
    END IF;
    v_def := pg_catalog.replace(v_def, 'La venta o unidad ya tiene una entrega efectiva', 'La venta ya tiene una entrega efectiva');
    EXECUTE v_def;
  END IF;
END
$hu032_permitir_reentrega$;

